# The loop
# --------------------------------------------------------------------------- #


@dataclass
class HealResult:
    status: str                                       # passed | healed | failed | skipped
    driver: str | None = None
    rounds: int = 0
    fixes: list[dict] = field(default_factory=list)
    remaining: list[str] = field(default_factory=list)
    warnings: int = 0
    note: str | None = None

    def as_dict(self) -> dict:
        return {"status": self.status, "driver": self.driver, "rounds": self.rounds, "fixes": self.fixes,
                "remaining": self.remaining, "warnings": self.warnings, "note": self.note}


def generated_files(root: Path, out_dir: Path) -> list[str]:
    files = []
    for f in sorted(out_dir.rglob("*.sol")):
        try:
            if MARKER in f.read_bytes()[:4096]:
                files.append(f.resolve().relative_to(root.resolve()).as_posix())
        except (OSError, ValueError):
            continue
    return files


def _line_bounds(data: bytes, start: int, end: int) -> tuple[int, int]:
    ls = data.rfind(b"\n", 0, start) + 1
    le = data.find(b"\n", end)
    return ls, (len(data) if le < 0 else le)


def apply_edits(path: Path, data: bytes, edits: list[Edit], log_: HealLog | None) -> tuple[bytes, list[dict]]:
    """Apply non-overlapping edits from the end of the file backwards; record each as a line change."""
    done = []
    last_start = len(data) + 1
    for ed in sorted(edits, key=lambda x: (x.start, x.end), reverse=True):
        if ed.end > last_start or (ed.end == last_start and ed.start == ed.end == last_start):
            continue  # overlaps an edit already applied this round; the next compile reports it again
        ls, le = _line_bounds(data, ed.start, ed.end)
        old = data[ls:le]
        new_data = data[:ed.start] + ed.text + data[ed.end:]
        new = new_data[ls:le + len(ed.text) - (ed.end - ed.start)]
        data = new_data
        last_start = ed.start
        line = data[:ls].count(b"\n") + 1
        done.append({"rule": ed.rule, "line": line, "old": old.decode("utf-8", "replace").strip(),
                     "new": new.decode("utf-8", "replace").strip()})
        if log_ is not None:
            log_.add(path, ed.rule, old.decode("utf-8", "replace"), new.decode("utf-8", "replace"))
    return data, done


def heal(root: Path, out_dir: Path, driver: str = "auto", solc: str | None = None,
         max_rounds: int = DEFAULT_ROUNDS, warnings: bool = True, compile_fn=None) -> HealResult:
    """Compile the generated suites under ``out_dir`` and rewrite them until they build."""
    root = root.resolve()
    out_dir = out_dir.resolve()
    files = generated_files(root, out_dir)
    if not files:
        return HealResult("skipped", note="no generated files to compile")
    compile_fn = compile_fn or (lambda: compile_generated(root, files, driver, solc))
    generated = set(files)
    heal_log = HealLog.load(out_dir)
    result = HealResult("passed")
    build = None
    for rnd in range(1, max_rounds + 2):
        build = compile_fn()
        result.driver = build.driver
        if not build.readable:
            result.status, result.note = "skipped", build.note
            return result
        result.rounds = rnd
        unresolved = [p for p in build.errors if _is_unresolved_import(p)]
        if unresolved:
            result.status = "skipped"
            result.note = "imports did not resolve, so the suites could not be compiled here: " + unresolved[0].message
            return result
        if rnd > max_rounds:
            break
        fixable = [p for p in build.problems if p.file in generated and (p.severity == "error" or warnings)]
        if not build.errors and not fixable:
            break
        per_file: dict[str, list[Edit]] = {}
        sources: dict[str, bytes] = {}
        for p in fixable:
            if p.file not in sources:
                sources[p.file] = (root / p.file).read_bytes()
            ed = edit_for(sources[p.file], p, build.version, warnings)
            if ed is not None:
                per_file.setdefault(p.file, []).append(ed)
        if not per_file:
            break
        for f, edits in per_file.items():
            path = root / f
            data, done = apply_edits(path, sources[f], edits, heal_log)
            path.write_bytes(data)
            for d in done:
                result.fixes.append({"file": f, **d})
        heal_log.save()
    assert build is not None
    result.warnings = sum(1 for p in build.problems if p.severity == "warning")
    if build.errors:
        result.status = "failed"
        result.remaining = [p.describe(root) for p in build.errors]
    elif result.fixes:
        result.status = "healed"
    return result


def _is_unresolved_import(p: Problem) -> bool:
    return p.severity == "error" and (p.code == "6275" or (p.type == "ParserError" and "not found" in p.message
                                                          and ("Source" in p.message or "File" in p.message)))


def summarize(result: HealResult, out=None) -> None:
    import sys
    out = out or sys.stderr
    if result.status == "skipped":
        print(f"foundryguard: build check skipped ({result.note})", file=out)
        return
    for f in result.fixes:
        print(f"foundryguard: healed {f['file']}:{f['line']} [{f['rule']}] {f['old']}  ->  {f['new']}", file=out)
    if result.status == "failed":
        print(f"foundryguard: generated suites still do not compile after {result.rounds} compile(s) "
              f"[{result.driver}]:", file=out)
        for r in result.remaining:
            print(f"  {r}", file=out)
    else:
        what = f"{len(result.fixes)} fix(es), {result.rounds} compile(s)" if result.fixes else "no fixes needed"
        print(f"foundryguard: generated suites compile [{result.driver}], {what}", file=out)
