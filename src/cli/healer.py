#!/usr/bin/env python3
"""FoundryGuard healer: compile the generated suites and repair what the local compiler rejects.

Generated files are rendered from templates that target "a recent solc 0.8". A project
pinned to another version, or a stricter set of checks, can still reject a line: a pragma
the installed solc does not satisfy, a missing data location, a visibility or override
specifier one version wants and another refuses, a state mutability the compiler wants
tightened or relaxed.

The loop is Generate -> Compile -> Heal -> Re-compile:

1. the generated ``.sol`` files under the output dir are compiled with ``forge build --json``
   (when forge is on PATH) or with solc / solcjs through Standard JSON;
2. every diagnostic that points into a generated file is matched against the rules below;
   a rule turns it into a small byte-level edit at the reported source location;
3. the edits are applied and the files compiled again, until no error is left, no rule
   applies, or ``max_rounds`` is reached.

Only files that carry the ``@generated by FoundryGuard`` marker are ever touched. Errors in
the project's own sources are reported, never edited.

Every edit is recorded in ``<out>/foundryguard.heal.json`` as an (old line, new line) pair.
The injector replays that log when it renders the suites again, so ``gen --force`` and
``check`` produce the healed text and a healed suite is not reported as stale.
"""

from __future__ import annotations

import json
import logging
import re
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

if __package__:
    from . import compiler
else:
    import compiler  # type: ignore

log = logging.getLogger("foundryguard.healer")

HEAL_FILE = "foundryguard.heal.json"
HEAL_SCHEMA = "foundryguard.heal/v1"
MARKER = b"// @generated by FoundryGuard"
DEFAULT_ROUNDS = 5
DRIVERS = ("auto", "forge", "solc", "solcjs")

ANSI = re.compile(r"\x1b\[[0-9;]*m")
IDENT = r"[A-Za-z_$][\w$]*"
LOCATIONS = ("memory", "calldata", "storage")


# --------------------------------------------------------------------------- #
# Heal log (replayed by the injector)
# --------------------------------------------------------------------------- #


class HealLog:
    """Line replacements per generated file, relative to the output dir."""

    def __init__(self, path: Path, entries: dict[str, list[dict]] | None = None):
        self.path = path
        self.entries: dict[str, list[dict]] = entries or {}

    @classmethod
    def load(cls, out_dir: Path) -> "HealLog":
        path = out_dir / HEAL_FILE
        try:
            data = json.loads(path.read_text())
        except (OSError, ValueError):
            return cls(path)
        files = data.get("files") if isinstance(data, dict) else None
        if not isinstance(files, dict):
            return cls(path)
        clean = {k: [e for e in v if isinstance(e, dict) and isinstance(e.get("old"), str) and isinstance(e.get("new"), str)]
                 for k, v in files.items() if isinstance(v, list)}
        return cls(path, clean)

    def key(self, file: Path) -> str:
        try:
            return file.resolve().relative_to(self.path.parent.resolve()).as_posix()
        except ValueError:
            return file.as_posix()

    def apply(self, file: Path, content: str) -> str:
        for e in self.entries.get(self.key(file), []):
            if e["old"] in content:
                content = content.replace(e["old"], e["new"], 1)
        return content

    def add(self, file: Path, rule: str, old: str, new: str) -> None:
        self.entries.setdefault(self.key(file), []).append({"rule": rule, "old": old, "new": new})

    def save(self) -> None:
        if not any(self.entries.values()):
            return
        payload = {"schema": HEAL_SCHEMA, "files": {k: v for k, v in sorted(self.entries.items()) if v}}
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_text(json.dumps(payload, indent=2) + "\n")


# --------------------------------------------------------------------------- #
# Compiling the generated files
# --------------------------------------------------------------------------- #


@dataclass
class Problem:
    """One compiler diagnostic, reduced to what the rules need."""
    severity: str
    type: str
    code: str
    message: str
    file: str | None
    start: int | None
    end: int | None

    def where(self, root: Path) -> str:
        if not self.file:
            return "<project>"
        if self.start is None:
            return self.file
        line, col = compiler._line_col(root, self.file, self.start)
        return f"{self.file}:{line}:{col}" if line else self.file

    def describe(self, root: Path) -> str:
        code = f" ({self.code})" if self.code else ""
        return f"{self.where(root)}: {self.type}{code}: {self.message}"


@dataclass
class Build:
    driver: str
    version: str | None
    problems: list[Problem]
    readable: bool = True     # False when the compiler output could not be read at all
    note: str | None = None

    @property
    def errors(self) -> list[Problem]:
        return [p for p in self.problems if p.severity == "error"]


def problems_from_json(output: dict) -> list[Problem]:
    out = []
    for e in output.get("errors", []) or []:
        if not isinstance(e, dict):
            continue
        loc = e.get("sourceLocation") or {}
        start = loc.get("start") if isinstance(loc.get("start"), int) and loc["start"] >= 0 else None
        end = loc.get("end") if isinstance(loc.get("end"), int) and loc["end"] >= 0 else None
        out.append(Problem(severity=str(e.get("severity", "error")).lower(), type=e.get("type", "Error"),
                           code=str(e.get("errorCode") or ""), message=(e.get("message") or "").strip(),
                           file=loc.get("file") or None, start=start, end=end))
    return out


TEXT_DIAG = re.compile(r"^(Error|Warning|Info)(?: \((\d+)\))?: (.+?)\n\s*--> ([^\n]+?):(\d+):(\d+):", re.M)


def problems_from_text(text: str, root: Path) -> list[Problem]:
    """Fallback for forge versions that print formatted diagnostics instead of JSON."""
    out = []
    for m in TEXT_DIAG.finditer(ANSI.sub("", text)):
        sev, code, msg, file, line, col = m.groups()
        start = _offset(root, file.strip(), int(line), int(col))
        out.append(Problem(severity=sev.lower(), type=sev, code=code or "", message=msg.strip(),
                           file=file.strip(), start=start, end=None))
    return out


def _offset(root: Path, file: str, line: int, col: int) -> int | None:
    data = compiler.read_source(root, file)
    if data is None:
        return None
    pos = 0
    for _ in range(line - 1):
        nl = data.find(b"\n", pos)
        if nl < 0:
            return None
        pos = nl + 1
    return pos + col - 1


def _json_document(text: str) -> dict | None:
    start = text.find("{")
    while start >= 0:
        try:
            doc, _ = json.JSONDecoder().raw_decode(text[start:])
        except ValueError:
            start = text.find("{", start + 1)
            continue
        if isinstance(doc, dict):
            return doc
        start = text.find("{", start + 1)
    return None


def compile_forge(root: Path, files: list[str]) -> Build:
    forge = shutil.which("forge")
    if not forge:
        return Build("forge", None, [], readable=False, note="forge is not on PATH")
    cmd = [forge, "build", "--json", "--root", str(root), *[str(root / f) for f in files]]
    log.info("running %s", " ".join(cmd))
    try:
        proc = subprocess.run(cmd, cwd=root, capture_output=True, text=True, timeout=compiler.COMPILE_TIMEOUT)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return Build("forge", None, [], readable=False, note=f"forge build did not run: {exc}")
    doc = _json_document(proc.stdout)
    if doc is not None and "errors" in doc:
        return Build("forge", None, problems_from_json(doc))
    problems = problems_from_text(proc.stdout + "\n" + proc.stderr, root)
    if problems or proc.returncode == 0:
        return Build("forge", None, problems)
    tail = (proc.stderr or proc.stdout).strip()[-600:]
    return Build("forge", None, [], readable=False, note=f"could not read forge build output: {tail}")


def compile_solc(root: Path, files: list[str], kind: str = "auto", explicit: str | None = None) -> Build:
    profile = compiler.foundry_profile(root)
    wanted = str(profile.get("solc_version") or profile.get("solc") or "") or None
    if wanted and not wanted[:1].isdigit():
        explicit, wanted = explicit or wanted, None
    candidates = compiler.order_candidates(compiler.discover_compilers(kind, explicit), wanted)
    if not candidates:
        return Build(kind, None, [], readable=False, note="no Solidity compiler found")
    cand = candidates[0]
    remappings = compiler.load_remappings(root)
    payload = compiler.standard_json_input(root, files, remappings, False, profile.get("evm_version"))
    try:
        output = compiler.run_standard_json(cand, root, payload, remappings)
    except compiler.SolidityError as exc:
        return Build(cand.kind, cand.version, [], readable=False, note=exc.headline)
    return Build(cand.kind, cand.version, problems_from_json(output))


def compile_generated(root: Path, files: list[str], driver: str = "auto", solc: str | None = None) -> Build:
    if driver == "forge" or (driver == "auto" and shutil.which("forge")):
        return compile_forge(root, files)
    return compile_solc(root, files, "auto" if driver == "auto" else driver, solc)


