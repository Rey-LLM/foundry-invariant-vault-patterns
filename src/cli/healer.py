# Rules: diagnostic -> byte edit
# --------------------------------------------------------------------------- #


@dataclass
class Edit:
    start: int
    end: int
    text: bytes
    rule: str


def _header(src: bytes, start: int) -> tuple[int, int] | None:
    """[start, end) of a function header (`function ... ` up to `{` or `;`), from any offset inside it."""
    hs = None
    for m in re.finditer(rb"\b(function|constructor|modifier|fallback|receive)\b", src[:start + 12]):
        if m.start() <= start:
            hs = m.start()
    if hs is None:
        return None
    depth = 0
    for i in range(hs, len(src)):
        c = src[i:i + 1]
        if c == b"(":
            depth += 1
        elif c == b")":
            depth -= 1
        elif depth == 0 and c in (b"{", b";"):
            return hs, i
    return None


def _params_close(src: bytes, hs: int, he: int) -> int | None:
    """Offset just after the `)` that closes the parameter list."""
    open_ = src.find(b"(", hs, he)
    if open_ < 0:
        return None
    depth = 0
    for i in range(open_, he):
        if src[i:i + 1] == b"(":
            depth += 1
        elif src[i:i + 1] == b")":
            depth -= 1
            if depth == 0:
                return i + 1
    return None


def _before_returns(src: bytes, hs: int, he: int) -> int:
    """Where a new specifier goes: before `returns`, else before the body (trailing space kept)."""
    m = re.search(rb"\breturns\b", src[hs:he])
    pos = hs + m.start() if m else he
    while pos > hs and src[pos - 1:pos] in (b" ", b"\t", b"\n", b"\r"):
        pos -= 1
    return pos


def _decl_span(src: bytes, p: Problem) -> tuple[int, int]:
    if p.end is not None and p.end > p.start:
        return p.start, p.end
    depth = 0
    for i in range(p.start, len(src)):
        c = src[i:i + 1]
        if c in (b"(", b"["):
            depth += 1
        elif c in (b")", b"]"):
            if depth == 0:
                return p.start, i
            depth -= 1
        elif depth == 0 and c in (b",", b";", b"="):
            return p.start, i
    return p.start, len(src)


def _quoted(message: str) -> list[str]:
    return re.findall(r'"([^"]+)"', message)


def rule_pragma(src: bytes, p: Problem, version: str | None) -> Edit | None:
    if "requires different compiler version" not in p.message:
        return None
    m = re.search(r"current compiler is (\d+\.\d+\.\d+)", p.message)
    current = m.group(1) if m else version
    if not current:
        return None
    current = ".".join(str(n) for n in compiler.parse_version(current))
    s, e = (p.start, p.end) if p.end is not None else (p.start, src.find(b";", p.start) + 1)
    if not src[s:e].startswith(b"pragma"):
        found = re.search(rb"pragma\s+solidity[^;]*;", src)
        if not found:
            return None
        s, e = found.span()
    return Edit(s, e, f"pragma solidity ^{current};".encode(), "pragma")


def rule_data_location(src: bytes, p: Problem, version: str | None) -> Edit | None:
    msg = p.message
    if not msg.startswith("Data location"):
        return None
    s, e = _decl_span(src, p)
    decl = src[s:e]
    if "can only be specified for" in msg:
        new = re.sub(rb"\s+(memory|calldata|storage)\b", b"", decl, count=1)
        return Edit(s, e, new, "data-location") if new != decl else None
    options = [q for q in _quoted(msg) if q in LOCATIONS]
    m = re.search(r'but "(\w+)" was given', msg)
    given = m.group(1) if m else None
    allowed = [o for o in options if o != given]
    if not allowed:
        return None
    loc = ("memory" if "memory" in allowed else allowed[0]).encode()
    if given:
        new = re.sub(rb"\b" + given.encode() + rb"\b", loc, decl, count=1)
        return Edit(s, e, new, "data-location") if new != decl else None
    named = re.match(rb"^(.*?\S)(\s+)(" + IDENT.encode() + rb")\s*$", decl, re.S)
    if named and named.group(3) not in (b"indexed",) and not named.group(1).endswith((b",", b"(")):
        new = named.group(1) + b" " + loc + b" " + named.group(3)
    else:
        new = decl.rstrip() + b" " + loc
    return Edit(s, e, new, "data-location")


def rule_visibility(src: bytes, p: Problem, version: str | None) -> Edit | None:
    msg = p.message
    head = _header(src, p.start) if p.start is not None else None
    if not head:
        return None
    hs, he = head
    if msg.startswith("No visibility specified"):
        q = _quoted(msg)
        vis = (q[0] if q else "public").encode()
        close = _params_close(src, hs, he)
        if close is None:
            return None
        return Edit(close, close, b" " + vis, "visibility")
    if msg.startswith("Free functions cannot have visibility") or "cannot have visibility" in msg:
        text = src[hs:he]
        new = re.sub(rb"\s+(public|external|internal|private)\b", b"", text, count=1)
        return Edit(hs, he, new, "visibility") if new != text else None
    if "must be declared external" in msg or 'Visibility for constructor is ignored' in msg:
        text = src[hs:he]
        repl = b"" if "constructor" in msg else b" external"
        new = re.sub(rb"\s+(public|internal|private)\b", repl, text, count=1)
        return Edit(hs, he, new, "visibility") if new != text else None
    return None


def rule_override(src: bytes, p: Problem, version: str | None) -> Edit | None:
    msg = p.message
    head = _header(src, p.start) if p.start is not None else None
    if not head:
        return None
    hs, he = head
    text = src[hs:he]
    if "does not override anything" in msg:
        new = re.sub(rb"\s+override\b(\s*\([^)]*\))?", b"", text, count=1)
        return Edit(hs, he, new, "override") if new != text else None
    if "needs to specify overridden contract" in msg:
        bases = ", ".join(_quoted(msg)).encode()
        if not bases:
            return None
        spec = b"override(" + bases + b")"
        if re.search(rb"\boverride\b", text):
            new = re.sub(rb"\boverride\b(\s*\([^)]*\))?", spec, text, count=1)
            return Edit(hs, he, new, "override")
        pos = _before_returns(src, hs, he)
        return Edit(pos, pos, b" " + spec, "override")
    if 'missing "override" specifier' in msg:
        if re.search(rb"\boverride\b", text):
            return None
        pos = _before_returns(src, hs, he)
        return Edit(pos, pos, b" override", "override")
    if 'missing "virtual"' in msg or "must be marked \"virtual\"" in msg:
        if re.search(rb"\bvirtual\b", text):
            return None
        pos = _before_returns(src, hs, he)
        return Edit(pos, pos, b" virtual", "override")
    return None


def rule_mutability(src: bytes, p: Problem, version: str | None) -> Edit | None:
    msg = p.message
    head = _header(src, p.start) if p.start is not None else None
    if not head:
        return None
    hs, he = head
    text = src[hs:he]
    if "cannot be declared as view" in msg or "cannot be declared as pure" in msg \
            or ("declared as view" in msg and "modifies the state" in msg):
        new = re.sub(rb"\s+(view|pure)\b", b"", text, count=1)
        return Edit(hs, he, new, "mutability") if new != text else None
    if "declared as pure" in msg and 'requires "view"' in msg:
        new = re.sub(rb"\bpure\b", b"view", text, count=1)
        return Edit(hs, he, new, "mutability") if new != text else None
    m = re.match(r"Function state mutability can be restricted to (view|pure)", msg)
    if m:
        want = m.group(1).encode()
        if re.search(rb"\b(view|pure)\b", text):
            new = re.sub(rb"\b(view|pure)\b", want, text, count=1)
            return Edit(hs, he, new, "mutability") if new != text else None
        pos = _before_returns(src, hs, he)
        return Edit(pos, pos, b" " + want, "mutability")
    return None


def rule_unused_param(src: bytes, p: Problem, version: str | None) -> Edit | None:
    if not p.message.startswith("Unused function parameter"):
        return None
    s, e = _decl_span(src, p)
    decl = src[s:e]
    m = re.match(rb"^(.*\S)(\s+)(" + IDENT.encode() + rb")\s*$", decl, re.S)
    if not m or m.group(3) in (b"memory", b"calldata", b"storage"):
        return None
    return Edit(s, e, m.group(1) + b" /* " + m.group(3) + b" */", "unused-parameter")


def rule_duplicate(src: bytes, p: Problem, version: str | None) -> Edit | None:
    """`Visibility already specified`, `State mutability already specified`, `Override already specified`."""
    if "already specified" not in p.message or p.start is None:
        return None
    m = re.match(rb"(public|external|internal|private|view|pure|payable|nonpayable|virtual|override)\b(\s*\([^)]*\))?",
                 src[p.start:])
    if not m:
        return None
    s = p.start
    while s > 0 and src[s - 1:s] in (b" ", b"\t"):
        s -= 1
    return Edit(s, p.start + m.end(), b"", "duplicate-specifier")


def rule_license(src: bytes, p: Problem, version: str | None) -> Edit | None:
    if "SPDX license identifier not provided" not in p.message or b"SPDX-License-Identifier" in src:
        return None
    return Edit(0, 0, b"// SPDX-License-Identifier: MIT\n", "license")


ERROR_RULES = (rule_pragma, rule_duplicate, rule_data_location, rule_visibility, rule_override, rule_mutability)
WARNING_RULES = (rule_mutability, rule_visibility, rule_unused_param, rule_license)


def edit_for(src: bytes, p: Problem, version: str | None, warnings: bool) -> Edit | None:
    rules = ERROR_RULES if p.severity == "error" else (WARNING_RULES if warnings else ())
    if p.start is None and not (p.severity != "error" and "SPDX" in p.message):
        return None
    for rule in rules:
        edit = rule(src, p, version)
        if edit is not None:
            return edit
    return None


