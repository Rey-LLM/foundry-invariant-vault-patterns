def _http_post(url: str, headers: dict, body: dict, timeout: int) -> dict:
    req = urllib.request.Request(url, data=json.dumps(body).encode(), method="POST",
                                 headers={"content-type": "application/json", **headers})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return json.loads(resp.read().decode())
    except urllib.error.HTTPError as e:
        detail = e.read().decode(errors="replace")[:300]
        raise AIError(f"provider returned HTTP {e.code}: {detail}") from None
    except (urllib.error.URLError, TimeoutError, OSError) as e:
        raise AIError(f"could not reach the provider: {e}") from None
    except json.JSONDecodeError:
        raise AIError("provider answered with something that is not JSON") from None


def complete(settings: AISettings, system: str, user: str, transport: Transport | None = None) -> str:
    send = transport or _http_post
    if settings.provider == "anthropic":
        data = send(f"{settings.base_url}/v1/messages",
                    {"x-api-key": settings.api_key, "anthropic-version": "2023-06-01"},
                    {"model": settings.model, "max_tokens": settings.max_tokens, "system": system,
                     "messages": [{"role": "user", "content": user}]},
                    settings.timeout)
        text = "".join(b.get("text", "") for b in data.get("content", []) if b.get("type") == "text")
    else:
        data = send(f"{settings.base_url}/chat/completions",
                    {"authorization": f"Bearer {settings.api_key}"},
                    {"model": settings.model, "max_tokens": settings.max_tokens,
                     "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}]},
                    settings.timeout)
        choices = data.get("choices") or [{}]
        text = (choices[0].get("message") or {}).get("content") or ""
    if not text.strip():
        raise AIError(f"empty answer from {settings.describe()}: {json.dumps(data)[:300]}")
    return text


# --------------------------------------------------------------------------- #
# Answer parsing and checks
# --------------------------------------------------------------------------- #

BLOCK_RE = re.compile(r"```(?:solidity|sol)?[ \t]*\n(.*?)```", re.S)
FILE_RE = re.compile(r"^\s*//\s*File:\s*(\S+)\s*$", re.M)


def split_files(answer: str) -> dict[str, str]:
    """Code blocks by file name; unlabelled blocks are taken as Handler.sol then Invariant.t.sol."""
    files: dict[str, str] = {}
    unnamed = ["Handler.sol", "Invariant.t.sol"]
    for block in BLOCK_RE.findall(answer):
        block = block.strip()
        m = FILE_RE.match(block.split("\n", 1)[0])
        if m:
            name, block = m.group(1), block.split("\n", 1)[1] if "\n" in block else ""
        else:
            name = next((u for u in unnamed if u not in files), None)
        if name and name not in files:
            files[name] = block.strip() + "\n"
    return files


def check_source(src: str, file: str, must_define: str, must_import: str | None) -> list[str]:
    problems = []
    code = strip_comments(src)
    if not re.search(r"^\s*pragma solidity\b", code, re.M):
        problems.append(f"{file}: no pragma")
    if not re.search(rf"\bcontract\s+{re.escape(must_define)}\b", code):
        problems.append(f"{file}: does not define contract {must_define}")
    if must_import and must_import not in code:
        problems.append(f"{file}: does not import the target from {must_import}")
    for rx, why in FORBIDDEN:
        if rx.search(code):
            problems.append(f"{file}: uses {why}")
    return problems


def header(layout: dict, settings: AISettings) -> str:
    return (f"{GENERATED_MARKER} ({settings.describe()}) for {layout['name']} ({layout['file']}).\n"
            "// No FoundryGuard preset matched this contract, so a language model wrote this file.\n"
            "// Read it before relying on it: check that every invariant is a real property of the contract.\n")


def generate(contract: dict, functions: list[dict], lineage: list[str], root: Path, import_rel: str,
             support_rel: str, settings: AISettings, transport: Transport | None = None) -> AIResult:
    """Ask the model for Handler.sol and Invariant.t.sol; raise AIError if the answer is unusable."""
    name = re.sub(r"\W", "_", contract["name"])
    handler_name, test_name = f"{name}AIHandler", f"{name}AIInvariantTest"
    layout = describe_contract(contract, functions, lineage, root, settings.max_source_chars)
    answer = complete(settings, SYSTEM_PROMPT, build_prompt(layout, handler_name, test_name, import_rel, support_rel),
                      transport)
    files = split_files(answer)
    handler, invariant = files.get("Handler.sol"), files.get("Invariant.t.sol")
    if not handler or not invariant:
        raise AIError(f"answer from {settings.describe()} did not contain Handler.sol and Invariant.t.sol")
    problems = check_source(handler, "Handler.sol", handler_name, import_rel)
    problems += check_source(invariant, "Invariant.t.sol", test_name, None)
    if not re.search(r"\bfunction\s+invariant_\w+", invariant):
        problems.append("Invariant.t.sol: no invariant_* function")
    if problems:
        raise AIError("generated suite refused: " + "; ".join(problems))
    top = header(layout, settings)
    return AIResult(handler=top + handler, invariant=top + invariant, handler_name=handler_name,
                    test_name=test_name, model=settings.describe(),
                    invariants=re.findall(r"\bfunction\s+(invariant_\w+)", invariant))
