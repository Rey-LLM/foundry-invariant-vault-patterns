#!/usr/bin/env python3
"""FoundryGuard Layer 06: LLM-written invariant suites for contracts no preset understands.

The presets in ``injector.py`` only fire when the blueprint proves they apply (ERC-4626, deposit /
withdraw / stake flows, hooks, transient storage). A contract with custom logic, an auction, a
bonding curve, a vesting schedule, gets nothing. With ``--ai`` the injector hands those contracts
to this module, which:

1. builds a compact description of the contract from the blueprint: lineage, constructor, every
   public/external function with modifiers and mutability, state variables, and the contract's own
   source with comments and blank lines stripped (capped at ``max_source_chars``);
2. sends it to an Anthropic or OpenAI-compatible chat endpoint with a fixed brief: write a bounded
   fuzz handler with ghost variables and an invariant test for this contract;
3. checks the answer before anything touches disk: both contracts present under the expected names,
   the target imported, and no cheatcode that reaches outside the EVM (``vm.ffi``, file and env
   access, RPC forks). A rejected answer writes nothing and the reason ends up in the report.

Nothing is sent unless the user asks for it (``--ai`` or ``[ai] enabled = true``) and a key is set:

    ANTHROPIC_API_KEY or OPENAI_API_KEY                   which provider to use (Anthropic wins if both)
    FOUNDRYGUARD_AI_PROVIDER=anthropic|openai              force one
    FOUNDRYGUARD_AI_MODEL                                  model name
    ANTHROPIC_BASE_URL / OPENAI_BASE_URL                   proxies, Azure, local OpenAI-compatible servers

The generated files are a starting point. They carry a header saying so and must be read before
anyone relies on them.
"""

from __future__ import annotations

import json
import os
import re
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

GENERATED_MARKER = "// @generated by FoundryGuard AI"
DEFAULT_MODELS = {"anthropic": "claude-sonnet-5-5", "openai": "gpt-4.1"}
DEFAULT_BASE_URLS = {"anthropic": "https://api.anthropic.com", "openai": "https://api.openai.com/v1"}
DEFAULT_TIMEOUT = 120
DEFAULT_MAX_TOKENS = 8000
DEFAULT_MAX_SOURCE_CHARS = 12000

# Cheatcodes that reach outside the EVM. A generated test that uses any of them is refused.
FORBIDDEN = [
    (re.compile(r"\bvm\s*\.\s*ffi\b"), "vm.ffi (runs shell commands)"),
    (re.compile(r"\bvm\s*\.\s*(readFile|readFileBinary|readLine|readDir|writeFile|writeFileBinary|writeLine|"
                r"writeJson|writeToml|removeFile|removeDir|createDir|copyFile|closeFile|fsMetadata|exists|isFile|isDir)\b"),
     "file system access"),
    (re.compile(r"\bvm\s*\.\s*(env\w*|setEnv)\b"), "environment variable access"),
    (re.compile(r"\bvm\s*\.\s*(rpc|rpcUrl\w*|createFork|createSelectFork|selectFork|makePersistent|transact)\b"),
     "network / fork access"),
    (re.compile(r"\bvm\s*\.\s*(broadcast|startBroadcast|stopBroadcast)\b"), "broadcasting transactions"),
    (re.compile(r"\bconsole2?\s*\.\s*log"), "console logging"),
]

SYSTEM_PROMPT = """You write Foundry invariant tests for Solidity smart contracts.
Answer with exactly two fenced ```solidity code blocks and nothing else. The first line of the first
block is `// File: Handler.sol`, the first line of the second is `// File: Invariant.t.sol`.

Rules:
- Use only forge-std (`import {Test} from "forge-std/Test.sol";`) and the imports given to you.
- The handler is a contract named exactly as requested, inheriting Test. It holds the target, a fixed
  set of actor addresses, and one public function per state-changing entry point of the target. Each
  handler function bounds its inputs with bound(), picks an actor from a seed, pranks as that actor,
  calls the target, and updates ghost variables that mirror what the contract should be tracking.
  Calls that are expected to revert for some inputs are made with try/catch so the run continues.
- The test contract is named exactly as requested, inherits Test, deploys the target and the handler
  in setUp(), calls targetContract(address(handler)) and restricts fuzzing to the handler selectors
  with targetSelector.
- Write invariant_* functions for the properties this specific contract must keep: conservation of
  value, monotonic counters, bounds on prices or rates, access control, state machine order, solvency.
  Each invariant has a one-line comment saying what bug it catches.
- No vm.ffi, no file, environment or RPC cheatcodes, no console logging, no external dependencies.
- If a constructor needs a token, deploy FoundryGuardMockERC20 from the support file (constructor
  takes name, symbol, decimals; it has mint(address,uint256), burn(address,uint256), approve,
  transfer, transferFrom, balanceOf, totalSupply).
- The code must compile with the given pragma. Prefer simple, readable code over clever code."""


class AIError(Exception):
    """The provider failed or its answer was refused. The message goes into the generation report."""


@dataclass
class AISettings:
    provider: str
    model: str
    api_key: str = field(repr=False)
    base_url: str
    timeout: int = DEFAULT_TIMEOUT
    max_tokens: int = DEFAULT_MAX_TOKENS
    max_source_chars: int = DEFAULT_MAX_SOURCE_CHARS

    def describe(self) -> str:
        return f"{self.provider}:{self.model}"


@dataclass
class AIResult:
    handler: str
    invariant: str
    handler_name: str
    test_name: str
    model: str
    invariants: list[str]


Transport = Callable[[str, dict, dict, int], dict]


# --------------------------------------------------------------------------- #
# Settings
# --------------------------------------------------------------------------- #


def settings_from(config: dict | None, env: dict | None = None) -> AISettings | None:
    """Provider settings from ``[ai]`` in foundryguard.toml and the environment; None without a key."""
    env = os.environ if env is None else env
    cfg = (config or {}).get("ai", {})
    provider = (env.get("FOUNDRYGUARD_AI_PROVIDER") or cfg.get("provider") or "").strip().lower()
    if not provider:
        provider = "anthropic" if env.get("ANTHROPIC_API_KEY") else ("openai" if env.get("OPENAI_API_KEY") else "")
    if not provider:
        return None
    if provider not in DEFAULT_MODELS:
        raise AIError(f"unknown AI provider '{provider}' (use anthropic or openai)")
    key = env.get("ANTHROPIC_API_KEY" if provider == "anthropic" else "OPENAI_API_KEY", "")
    if not key:
        return None
    base = env.get("ANTHROPIC_BASE_URL" if provider == "anthropic" else "OPENAI_BASE_URL") or cfg.get("base_url")
    return AISettings(
        provider=provider,
        model=env.get("FOUNDRYGUARD_AI_MODEL") or cfg.get("model") or DEFAULT_MODELS[provider],
        api_key=key,
        base_url=(base or DEFAULT_BASE_URLS[provider]).rstrip("/"),
        timeout=int(cfg.get("timeout", DEFAULT_TIMEOUT)),
        max_tokens=int(cfg.get("max_tokens", DEFAULT_MAX_TOKENS)),
        max_source_chars=int(cfg.get("max_source_chars", DEFAULT_MAX_SOURCE_CHARS)),
    )


# --------------------------------------------------------------------------- #
# Contract layout
# --------------------------------------------------------------------------- #


def _sig(fn: dict) -> str:
    params = ", ".join(f"{p['type']} {p.get('name') or ''}".strip() for p in fn.get("params", []))
    rets = ", ".join(r["type"] if isinstance(r, dict) else str(r) for r in fn.get("returns") or [])
    head = "constructor" if fn.get("kind") == "constructor" else f"function {fn['name']}"
    parts = [f"{head}({params})", fn.get("visibility", ""), fn.get("mutability", "")]
    parts += fn.get("modifiers", [])
    if rets:
        parts.append(f"returns ({rets})")
    return " ".join(p for p in parts if p and p != "nonpayable")


def strip_comments(src: str) -> str:
    """Drop comments and blank lines and collapse indentation; string literals are left alone."""
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        if c in "\"'":
            j = i + 1
            while j < n and src[j] != c:
                j += 2 if src[j] == "\\" else 1
            out.append(src[i:j + 1])
            i = j + 1
        elif src.startswith("//", i):
            while i < n and src[i] != "\n":
                i += 1
        elif src.startswith("/*", i):
            end = src.find("*/", i + 2)
            i = n if end < 0 else end + 2
        else:
            out.append(c)
            i += 1
    lines = (re.sub(r"\s+", " ", ln).strip() for ln in "".join(out).splitlines())
    return "\n".join(ln for ln in lines if ln)


def contract_source(root: Path, contract: dict) -> str:
    """The contract's own body, from its declaration line to the matching closing brace."""
    try:
        text = (root / contract["file"]).read_text(errors="replace")
    except OSError:
        return ""
    lines = text.splitlines(keepends=True)
    start = sum(len(ln) for ln in lines[:max(contract.get("line", 1) - 1, 0)])
    body = strip_comments(text[start:])
    depth, seen = 0, False
    for i, ch in enumerate(body):
        if ch == "{":
            depth, seen = depth + 1, True
        elif ch == "}":
            depth -= 1
            if seen and depth == 0:
                return body[:i + 1]
    return body


def describe_contract(contract: dict, functions: list[dict], lineage: list[str], root: Path,
                      max_source_chars: int = DEFAULT_MAX_SOURCE_CHARS) -> dict:
    """What the model sees: names and signatures from the blueprint, plus the trimmed source."""
    ctor = contract.get("constructor")
    src = contract_source(root, contract)
    truncated = len(src) > max_source_chars
    return {
        "name": contract["name"],
        "file": contract["file"],
        "pragma": contract.get("pragma") or "^0.8.20",
        "lineage": lineage,
        "constructor": _sig({**ctor, "kind": "constructor"}) if ctor else None,
        "functions": [_sig(f) for f in functions if f.get("visibility") in ("public", "external")],
        "state_vars": [f"{v['type']} {v.get('visibility', '')} {v['name']}".replace("  ", " ")
                       for v in contract.get("state_vars", [])],
        "source": src[:max_source_chars] + ("\n// ... truncated" if truncated else ""),
    }


def build_prompt(layout: dict, handler_name: str, test_name: str, import_rel: str, support_rel: str) -> str:
    lines = [
        f"Target contract: {layout['name']} ({layout['file']}), pragma solidity {layout['pragma']}.",
        f"Inheritance (most derived first): {', '.join(layout['lineage']) or layout['name']}.",
        f"Handler contract name: {handler_name}. Test contract name: {test_name}.",
        "Imports to use in both files:",
        f'  import {{{layout["name"]}}} from "{import_rel}";',
        f'  import {{FoundryGuardMockERC20}} from "{support_rel}";  // only if you need a token',
        '  import {Test} from "forge-std/Test.sol";',
        "The test file also imports the handler from \"./Handler.sol\".",
        "",
        f"Constructor: {layout['constructor'] or 'none'}",
        "Public/external functions (own and inherited):",
        *[f"  {s}" for s in layout["functions"]],
        "State variables:",
        *([f"  {s}" for s in layout["state_vars"]] or ["  none"]),
        "",
        "Source (comments removed):",
        "```solidity",
        layout["source"] or "// source not available",
        "```",
    ]
    return "\n".join(lines)


