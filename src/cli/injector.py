#!/usr/bin/env python3
"""FoundryGuard injector: turn a parser blueprint into Foundry invariant test suites.

For every deployable contract in the blueprint that exposes at least one
deposit, withdraw or staking/lock function (directly or through inheritance),
the injector writes::

    <out>/FoundryGuardSupport.sol        mock ERC-20, ERC-1967 proxy, token interface (shared)
    <out>/<Contract>/Handler.sol         fuzz handler: bounded inputs, actor pranking, ghost accounting
    <out>/<Contract>/Invariant.t.sol     invariant suite wired to the handler

The generated ``setUp`` works out of the box for the common cases:

* token constructor / initializer arguments (``IERC20 asset_``, ``address stakingToken`` ...) get a
  fresh ``FoundryGuardMockERC20``; every actor is minted a balance and approves the target;
* reward tokens are funded (``notifyRewardAmount``-style function when present, otherwise by minting
  to the target) and the funded amount becomes the bound of a rewards invariant;
* upgradeable contracts (``initialize`` + ``initializer``) are deployed behind an ERC-1967 proxy;
* the test contract deploys the target, so it is the owner of ``Ownable`` contracts. Admin-only
  functions (``onlyOwner``, ``onlyRole`` ...) are not fuzzed from actors.

Invariant presets are emitted only when the blueprint proves they apply:

* ERC-4626: previews honoured, positive deposits mint shares, vault solvency,
  ``convertToAssets(totalSupply) <= totalAssets``, assets/shares out <= in
* single-unit vaults: ``withdrawalsBoundedByDeposits``
* staking / ERC-20 accounting: actor balances <= reported total, token solvency
* rewards: rewards paid to actors never exceed what was funded
* hooks (Preset 04, ``blueprints/hook_reentrancy.py``): contracts that call external hooks mid-flow
  (Uniswap v4 style) get probe actors that check view consistency, the reentrancy lock and
  re-entry into ``nonReentrant`` flows while the callback is running
* transient storage (Preset 05, ``blueprints/transient_storage.py``): contracts that ``tstore`` in
  inline assembly are deployed as a ``<Contract>TransientHarness`` that can read its own transient
  slots; the handler checks after every call, and in multi-call sequences inside one transaction,
  that every slot is back to zero
* ``afterInvariant``: fails a run in which every value-flow call reverted

Contracts that match none of the presets but still have public state-changing functions (custom
logic: auctions, curves, vesting ...) are skipped. With ``--ai`` (or ``[ai] enabled = true``) and
``ANTHROPIC_API_KEY`` / ``OPENAI_API_KEY`` set, they are sent to ``ai_generator.py`` instead, which
asks a language model for a Handler.sol / Invariant.t.sol pair and checks it before writing.

Usage::

    python3 src/cli/injector.py foundryguard.json
    python3 src/cli/injector.py foundryguard.json --out test/foundryguard --contract StakingPool
    python3 src/cli/injector.py foundryguard.json --check        # CI: fail if suites are stale
    python3 src/cli/injector.py foundryguard.json --ai           # LLM fallback for custom contracts
"""

