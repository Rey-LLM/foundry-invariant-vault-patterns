    hname = f"{c['name']}GuardHandler"
    name = c["name"]
    ctor = c.get("constructor")
    invariant_names: list[str] = []
    payable_ctor = bool(ctor and ctor.get("mutability") == "payable")

    lines: list[str] = []
    hooks = t.hooks
    probe = hook_reentrancy.probe_name(name) if hooks else None
    if hooks:
        lines.append(f"// Preset 04: hook probes are deployed first so the target can be wired to hookProbes[0].")
        lines.append(f"for (uint256 i = 0; i < {meta.get('actors', 4)}; i++) {{")
        lines.append(f"    hookProbes.push(address(new {probe}()));")
        lines.append("}")
