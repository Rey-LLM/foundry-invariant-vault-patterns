            if f:
                arg = "REWARD_BUDGET" if len(f["params"]) == 1 else f"address({tk.var}), REWARD_BUDGET"
                lines.append(f"{tk.var}.mint(address(this), REWARD_BUDGET);")
                lines.append(f"{tk.var}.approve(address(target), REWARD_BUDGET);")
                lines.append(f"try target.{f['name']}({arg}) {{ }} catch {{")
                lines.append(f"    // {f['name']} expects the tokens up front instead of pulling them.")
