    deployed = plan.harness["name"] if plan.harness else name
    if plan.harness:
        lines.append(f"// Preset 05: {deployed} is {name} plus a view that reads its transient storage.")

    def deploy_expr(args: list[tuple[str, str]]) -> str:
        if not args:
            return f"address(new {deployed}())"
        return ("_deploy(abi.encodePacked(\n"
                f"            type({deployed}).creationCode,\n"
                "            abi.encode(\n"
                f"{_encode_args(args, '                ')}\n"
                "            )\n"
                "        ))")

    if plan.init_fn:
        init = plan.init_fn
        overloaded = sum(1 for f in t.functions if f["name"] == init["name"]) > 1
        if overloaded:
            sig = abi_signature(init)
            call = f'abi.encodeWithSignature("{sig}"' + ("" if not plan.init_args else ",\n" + _encode_args(plan.init_args, "                ")) + ")"
        else:
            call = f"abi.encodeWithSelector(\n                {name}.{init['name']}.selector" + (
                "" if not plan.init_args else ",\n" + _encode_args(plan.init_args, "                ")) + "\n            )"
        lines.append(f"// Upgradeable target: implementation behind an ERC-1967 proxy, initialised through {init['name']}().")
