def import_path(from_dir: Path, root: Path, src_file: str) -> str:
    rel = os.path.relpath(root / src_file, from_dir).replace(os.sep, "/")
    return rel if rel.startswith(".") else f"./{rel}"


def pragma_for(contract: dict) -> str:
    return contract.get("pragma") or DEFAULT_PRAGMA


def handler_fn_name(fn: dict, used: set[str]) -> str:
    base = fn["name"]
    name, k = base, 2
    while name in used:
        name, k = f"{base}_{k}", k + 1
    used.add(name)
    return name


def _q(s: str) -> str:
    return '"' + s.replace('"', '\\"') + '"'


