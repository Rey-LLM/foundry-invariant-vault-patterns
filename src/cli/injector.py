# Layer 08: line fixes the healer made for the local compiler, replayed on every render so a
# healed suite stays healed and `check` does not call it stale. Set by `inject`.
_HEALS: "healer.HealLog | None" = None


def write_file(path: Path, content: str, force: bool, dry_run: bool) -> str:
    if _HEALS is not None and path.suffix == ".sol":
        content = _HEALS.apply(path, content)
    if path.exists():
        existing = path.read_text()
        if existing == content:
            return "unchanged"
        if not force:
            return "kept (exists, use --force to overwrite)"
    if dry_run:
        return "would write"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    return "written"


def inject_ai(t: Target, root: Path, out_dir: Path, force: bool, dry_run: bool,
              ai: "ai_generator.AISettings", transport=None) -> dict:
    """Layer 06: a model-written suite for a contract no preset matched."""
    dest = (out_dir / t.name).resolve()
    entry = {
        "contract": t.name, "file": t.contract["file"], "line": t.contract["line"], "dir": dest.as_posix(),
        "flows": [], "skipped": [], "warnings": list(t.warnings), "setup_notes": [], "tokens": [],
        "upgradeable": False, "erc4626": False, "hooks": None, "transient": None,
        "pricing": None, "governance": None, "read_reentrancy": None, "support": None,
        "ai": {"model": ai.describe()}, "invariants": [],
    }
    files = [dest / "Handler.sol", dest / "Invariant.t.sol"]
    if dry_run:
        entry.update(handler="not checked (AI suites are not regenerated in dry runs)", invariant="not checked")
        return entry
    if not force and any(f.exists() for f in files):
        entry.update(handler="kept (exists, use --force to ask the model again)", invariant="kept")
        return entry
    try:
        res = ai_generator.generate(t.contract, t.functions, t.lineage, root, import_path(dest, root, t.contract["file"]),
                                    import_path(dest, out_dir.resolve(), SUPPORT_FILE), ai, transport)
    except ai_generator.AIError as e:
        log.warning("%s: AI generation failed: %s", t.name, e)
        entry.update(handler="not generated", invariant="not generated", blocked=[f"AI generation failed: {e}"])
        return entry
    entry["handler"] = write_file(files[0], res.handler, True, False)
    entry["invariant"] = write_file(files[1], res.invariant, True, False)
    entry["invariants"] = res.invariants
    entry["setup_notes"].append(f"suite written by {res.model}; review it before relying on it")
    return entry


def inject(blueprint: dict, root: Path, out_dir: Path, only: set[str] | None, actors: int,
           max_amount: str, force: bool, dry_run: bool, config: dict | None = None,
           ai: "ai_generator.AISettings | None" = None, ai_transport=None) -> list[dict]:
    global _HEALS
    _HEALS = healer.HealLog.load(out_dir)
    try:
        return _inject(blueprint, root, out_dir, only, actors, max_amount, force, dry_run, config, ai, ai_transport)
    finally:
        _HEALS = None


def _inject(blueprint: dict, root: Path, out_dir: Path, only: set[str] | None, actors: int,
            max_amount: str, force: bool, dry_run: bool, config: dict | None,
            ai: "ai_generator.AISettings | None", ai_transport) -> list[dict]:
    report = []
    unmatched: list[Target] = []
    targets = build_targets(blueprint, only, config, unmatched if ai else None)
    ecosystems = build_ecosystems(blueprint, only, config)
    # A contract whose constructor needs another project contract only works wired to it, so its suite is
    # the ecosystem one; a standalone suite would deploy it against a placeholder address.
    covered = {m.name: eco.suite for eco in ecosystems for m in eco.members if m.needs_members}
    targets = [t for t in targets if t.name not in covered]
    unmatched = [t for t in unmatched if t.name not in covered]
    support_status = None
    if targets or unmatched or ecosystems:
        support_status = write_file(out_dir / SUPPORT_FILE, render_support(), force, dry_run)
    for t in targets:
        dest = (out_dir / t.name).resolve()
        plan = plan_setup(t)
        entry = {
            "contract": t.name,
            "file": t.contract["file"],
            "line": t.contract["line"],
            "dir": dest.as_posix(),
            "flows": [f"{f['category']}:{f['signature']}" for f in t.flows],
            "skipped": [f"{s} ({r})" for s, r in t.skipped],
            "warnings": list(t.warnings),
            "setup_notes": list(plan.notes),
            "tokens": [{"var": tk.var, "role": tk.role, "param": tk.param} for tk in plan.tokens],
            "upgradeable": plan.init_fn is not None,
            "erc4626": t.is_erc4626,
            "hooks": t.hooks.summary() if t.hooks else None,
            "transient": t.transient.summary() if t.transient else None,
            "pricing": t.pricing.summary() if t.pricing else None,
            "governance": t.governance.summary() if t.governance else None,
            "read_reentrancy": t.read_reentrancy.summary() if t.read_reentrancy else None,
            "support": support_status,
        }
        if plan.blockers:
            entry.update(handler="not generated", invariant="not generated", invariants=[], blocked=plan.blockers)
            for b in plan.blockers:
                log.warning("%s: %s - set it in foundryguard.toml [contracts.%s]", t.name, b, t.name)
            report.append(entry)
            continue
        import_rel = import_path(dest, root, t.contract["file"])
        support_rel = import_path(dest, out_dir.resolve(), SUPPORT_FILE)
        handler_src, selectors, meta = render_handler(t, plan, import_rel, support_rel, actors, max_amount, dest, root)
        invariant_src, names = render_invariant(t, plan, import_rel, support_rel, selectors, meta)
        entry["handler"] = write_file(dest / "Handler.sol", handler_src, force, dry_run)
        entry["invariant"] = write_file(dest / "Invariant.t.sol", invariant_src, force, dry_run)
        entry["invariants"] = names
        report.append(entry)
    for eco in ecosystems:
        report.append(inject_ecosystem(eco, root, out_dir, force, dry_run, actors, max_amount, support_status))
    for t in unmatched:
        entry = inject_ai(t, root, out_dir, force, dry_run, ai, ai_transport)
        entry["support"] = support_status
        report.append(entry)
    return report


def is_stale(report: list[dict]) -> bool:
    for r in report:
        if r.get("ai"):  # model output is not reproducible, so it is never "stale"
            continue
        for key in ("handler", "invariant", "support"):
            if r.get(key) not in (None, "unchanged"):
                return True
    return False


def add_gen_args(ap: argparse.ArgumentParser) -> None:
    ap.add_argument("--out", help="output dir, relative to root (default: test/foundryguard)")
    ap.add_argument("--contract", action="append", help="only generate for this contract (repeatable)")
    ap.add_argument("--actors", type=int, help=f"number of fuzz actors (default: {DEFAULT_ACTORS})")
    ap.add_argument("--max-amount", help=f"upper bound for amount params (default: {DEFAULT_MAX_AMOUNT})")
    ap.add_argument("--force", action="store_true", help="overwrite existing files")
    ap.add_argument("--dry-run", action="store_true", help="print what would be generated without writing")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if any generated file is missing or stale")
    ap.add_argument("--json", action="store_true", help="print the generation report as JSON")
    ap.add_argument("--report-md", help="also write a Markdown summary (e.g. for $GITHUB_STEP_SUMMARY)")
    ap.add_argument("--sarif", help="also write setup warnings and skipped functions as SARIF")
    ap.add_argument("--no-ecosystem", action="store_true",
                    help="do not generate cross-contract ecosystem suites (Layer 07)")
    ap.add_argument("--ai", action="store_true",
                    help="send contracts no preset matches to an LLM (needs ANTHROPIC_API_KEY or OPENAI_API_KEY)")
    heal = ap.add_mutually_exclusive_group()
    heal.add_argument("--heal", dest="heal", action="store_true", default=None,
                      help="compile the generated suites and fix what the local compiler rejects "
                           "(default: on when forge is on PATH)")
    heal.add_argument("--no-heal", dest="heal", action="store_false", help="do not compile or heal the generated suites")
    ap.add_argument("--heal-compiler", choices=healer.DRIVERS,
                    help="compiler for the heal loop (default: forge if on PATH, else solc / solcjs)")
    ap.add_argument("--heal-rounds", type=int, help=f"maximum heal rounds (default: {healer.DEFAULT_ROUNDS})")


def gen_from_args(args: argparse.Namespace, blueprint: dict, config: dict, root: Path) -> int:
    gcfg = config.get("generate", {})
    actors = args.actors if args.actors is not None else int(gcfg.get("actors", DEFAULT_ACTORS))
    max_amount = str(args.max_amount or gcfg.get("max_amount", DEFAULT_MAX_AMOUNT))
    if actors < 1:
        raise SystemExit("foundryguard: --actors must be >= 1")
    if not re.fullmatch(r"\d+(e\d+)?", max_amount):
        raise SystemExit("foundryguard: --max-amount must be a Solidity number literal such as 1e24")
    out_dir = Path(args.out or gcfg.get("out", "test/foundryguard"))
    out_dir = out_dir if out_dir.is_absolute() else root / out_dir
    only = set(args.contract) if args.contract else None
    dry = args.dry_run or args.check
    if getattr(args, "no_ecosystem", False):
        config = {**config, "ecosystem": {**config.get("ecosystem", {}), "enabled": False}}
    ai = None
    if getattr(args, "ai", False) or config.get("ai", {}).get("enabled") is True:
        try:
            ai = ai_generator.settings_from(config)
        except ai_generator.AIError as e:
            raise SystemExit(f"foundryguard: {e}")
        if ai is None:
            print("foundryguard: AI fallback requested but neither ANTHROPIC_API_KEY nor OPENAI_API_KEY is set; "
                  "custom contracts are skipped", file=sys.stderr)
    report = inject(blueprint, root, out_dir, only, actors, max_amount, args.force or args.check, dry, config, ai)

    if args.report_md or args.sarif:
        rep = _reporting()
        if args.report_md:
            Path(args.report_md).write_text(rep.markdown_report(report, blueprint))
        if args.sarif:
            Path(args.sarif).write_text(json.dumps(rep.sarif_from_generation(report, root), indent=2) + "\n")

    healed = None
    hcfg = config.get("heal", {})
    want = args.heal if getattr(args, "heal", None) is not None else hcfg.get("enabled")
    if want is None:
        want = bool(shutil.which("forge"))
    if want and report and not dry:
        rounds = args.heal_rounds if getattr(args, "heal_rounds", None) is not None else int(hcfg.get("max_rounds", healer.DEFAULT_ROUNDS))
        healed = healer.heal(root, out_dir, getattr(args, "heal_compiler", None) or hcfg.get("compiler", "auto"),
                             getattr(args, "solc", None) or hcfg.get("solc"), max(rounds, 0),
                             bool(hcfg.get("warnings", True)))

    if args.json:
        print(json.dumps(report, indent=2))
    else:
        if not report:
            print("foundryguard: no contracts with drivable deposit/withdraw/stake_lock functions", file=sys.stderr)
        for r in report:
            via = f" [AI {r['ai']['model']}]" if r.get("ai") else ""
            print(f"{r['contract']}{via}: Handler.sol {r['handler']}, Invariant.t.sol {r['invariant']} -> {os.path.relpath(r['dir'])}")
            if r.get("ecosystem"):
                print("    matrix: " + "\n            ".join(r["ecosystem"]["matrix_text"].splitlines()))
            for f in r["flows"]:
                print(f"    + {f}")
            for a in r.get("actions", []):
                print(f"    ~ {a}")
            for s in r["skipped"]:
                print(f"    - {s}")
            for inv in r.get("invariants", []):
                print(f"    * {inv}")
            for w in r.get("warnings", []) + r.get("setup_notes", []) + r.get("blocked", []):
                print(f"    ! {w}")
    if healed is not None:
        healer.summarize(healed)
        if healed.status == "failed":
            return 1
    if args.check and is_stale(report):
        print("foundryguard: generated suites are missing or out of date (run `foundryguard gen --force`)", file=sys.stderr)
        return 1
    return 0


def _reporting():
    if __package__:
        from . import reporting  # type: ignore
    else:
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import reporting  # type: ignore
    return reporting


def _load_config(root: Path, path: str | None) -> dict:
    if __package__:
        from .parser import load_config  # type: ignore
    else:
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        from parser import load_config  # type: ignore
    return load_config(root, path)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="foundryguard-inject",
        description="Generate Foundry Handler.sol / Invariant.t.sol suites from a FoundryGuard blueprint.",
    )
    ap.add_argument("blueprint", nargs="?", default="foundryguard.json", help="blueprint from parser.py (default: foundryguard.json)")
    ap.add_argument("--root", help="project root (default: the root recorded in the blueprint)")
    ap.add_argument("--config", help="config file (default: <root>/foundryguard.toml if present)")
    add_gen_args(ap)
    ap.add_argument("-v", "--verbose", action="count", default=0)
    args = ap.parse_args(argv)

    logging.basicConfig(level=logging.WARNING - 10 * min(args.verbose, 2), format="%(levelname)s %(name)s: %(message)s")
    blueprint = load_blueprint(Path(args.blueprint))
    root = Path(args.root or blueprint.get("root") or ".").resolve()
    return gen_from_args(args, blueprint, _load_config(root, args.config), root)


if __name__ == "__main__":
    sys.exit(main())
