    if hooks:
        lines.append("for (uint256 i = 0; i < hookProbes.length; i++) {")
        lines.append(f"    {probe}(payable(hookProbes[i])).arm(address(target));")
        lines.append("}")
        if hooks.setter and not plan.hook_params:
            sig = abi_signature(hooks.setter)
            lines.append(f"// Register the probe as {name}'s hook (the test contract deployed the target, so it is the owner).")
