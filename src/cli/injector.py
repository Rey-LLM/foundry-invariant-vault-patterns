@dataclass
class SetupPlan:
    tokens: list[Token] = field(default_factory=list)
    ctor_args: list[tuple[str, str]] = field(default_factory=list)   # (expr, "type name")
    init_fn: dict | None = None
    init_args: list[tuple[str, str]] = field(default_factory=list)
    reward_funder: dict | None = None
    notes: list[str] = field(default_factory=list)
    blockers: list[str] = field(default_factory=list)
    hook_params: int = 0  # constructor / initializer parameters wired to the hook probe
    harness: dict | None = None  # Preset 05: {"name", "params", "args", "payable", "symbols"}


def _plan_args(params: list[dict], plan: SetupPlan, overrides: list[str] | None, where: str,
               hooks: "hook_reentrancy.HookPlan | None" = None) -> list[tuple[str, str]]:
    if overrides is not None:
        if len(overrides) != len(params):
            plan.blockers.append(f"{where}: config gives {len(overrides)} argument(s), the signature takes {len(params)}")
            return []
        return [(str(expr), f"{p['type']} {p['name']}") for expr, p in zip(overrides, params)]
    out = []
    used = {tk.var for tk in plan.tokens}
    for p in params:
        if hooks is not None and hook_reentrancy.is_hook_param(p):
            plan.hook_params += 1
            out.append(("hookProbes[0]", f"{p['type']} {p['name']}: Preset 04 hook probe"))
            continue
        if is_token_param(p):
            base = sol_ident(p["name"].strip("_")) or "token"
            var, k = base, 2
            while var in used or var in ("target", "handler", "tokens"):
                var, k = f"{base}{k}", k + 1
            used.add(var)
            plan.tokens.append(Token(var=var, role=token_role(p["name"]), param=p["name"], type=p["type"]))
            out.append((f"address({var})", f"{p['type']} {p['name']}"))
            continue
        expr, warn = default_value(p["type"], p["name"])
        if warn:
            (plan.blockers if expr is None else plan.notes).append(f"{where}: {warn}")
        out.append((expr or "0", f"{p['type']} {p['name']}"))
    return out


def plan_setup(t: Target) -> SetupPlan:
    plan = SetupPlan()
    ctor = t.contract.get("constructor")
    cfg = t.settings
    plan.ctor_args = _plan_args(ctor["params"] if ctor else [], plan, cfg.get("constructor_args"), "constructor", t.hooks)
    inits = [f for f in t.functions if f["name"].startswith("initialize")
             and any(INITIALIZER_MODIFIER.match(m) for m in f.get("modifiers", []))]
    if inits or cfg.get("initializer"):
        want = cfg.get("initializer")
        init = next((f for f in t.functions if f["signature"] == want or f["name"] == want), None) if want else inits[0]
        if init is None:
            plan.blockers.append(f"initializer '{want}' from foundryguard.toml not found")
        else:
            plan.init_fn = init
            plan.init_args = _plan_args(init["params"], plan, cfg.get("initializer_args"), init["name"], t.hooks)
    plan.reward_funder = next((f for f in t.functions if REWARD_FUNDERS.match(f["name"])
                               and [p["type"] for p in f["params"]] in (["uint256"], ["address", "uint256"])), None)
    # A reward token can also be a public state variable set elsewhere; we can only fund the ones we deploy.
    if t.hooks:
        plan.notes.extend(hook_reentrancy.wiring_notes(t.hooks, plan.hook_params, t.flows))
        plan.notes.extend(t.hooks.notes)
    if t.transient:
        plan.notes.extend(t.transient.notes)
        if t.transient.slots:
            plan.harness = plan_harness(t)
    return plan


# typeIdentifier prefixes of user-defined types; their names are imported from the target's own file.
USER_TYPE_IDS = ("t_contract$_", "t_enum$_", "t_userDefinedValueType$_", "t_struct$_")


def plan_harness(t: Target) -> dict:
    """Preset 05: the constructor of ``<Contract>TransientHarness``, forwarding the target's own.

    Parameter types are written as solc reports them. User-defined types (``IERC20``, ``Lib.Kind``) are
    imported from the file that declares the target, where they are already in scope.
    """
    ctor = t.contract.get("constructor")
    params, args, symbols = [], [], []
    for i, p in enumerate(ctor["params"] if ctor else []):
        name = f"{sol_ident(p['name'].strip('_')) or 'arg'}{i}"
        ptype, tid = p["type"], p.get("type_id") or ""
        if tid.startswith("t_address_payable") and ptype == "address":
            ptype = "address payable"
        base = re.sub(r"(\[\d*\])+$", "", ptype)
        if tid.startswith(USER_TYPE_IDS) or (USER_TYPE_RE.match(base.split(".")[0]) and not is_elementary(base)):
            sym = base.split(".")[0]
            if sym != t.name and sym not in symbols:
                symbols.append(sym)
        dynamic = ptype in ("string", "bytes") or ptype.endswith("]") or tid.startswith("t_struct$_")
        params.append(f"{ptype}{' memory' if dynamic else ''} {name}")
        args.append(name)
    return {"name": transient_storage.harness_name(t.name), "params": params, "args": args,
            "payable": bool(ctor and ctor.get("mutability") == "payable"), "symbols": symbols}


