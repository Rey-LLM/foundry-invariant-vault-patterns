@dataclass
class Token:
    var: str        # Solidity variable name in the test, e.g. "asset"
    role: str       # asset | staking | reward
    param: str      # constructor / initializer parameter it feeds
    type: str


@dataclass
class Target:
    contract: dict
    functions: list[dict]           # effective public/external functions (own + inherited)
    flows: list[dict]               # classified value-flow functions to drive
    skipped: list[tuple[str, str]] = field(default_factory=list)  # (signature, reason)
    getters: set[str] = field(default_factory=set)
    warnings: list[str] = field(default_factory=list)
    lineage: list[str] = field(default_factory=list)
    settings: dict = field(default_factory=dict)  # [contracts.<Name>] config block
    hooks: "hook_reentrancy.HookPlan | None" = None  # Preset 04 plan when the target calls out to hooks
    transient: "transient_storage.TransientPlan | None" = None  # Preset 05 plan when the target uses tstore
    pricing: "flashloan_price.FlashLoanPlan | None" = None  # Preset 06 plan when the price source is manipulable
    governance: "governance_flashmint.GovernancePlan | None" = None  # Preset 07 plan for a governance contract
    read_reentrancy: "read_reentrancy_view.ReadReentrancyPlan | None" = None  # Preset 08 payout-before-settle plan

    @property
    def name(self) -> str:
        return self.contract["name"]

    def fn(self, signature: str) -> dict | None:
        return next((f for f in self.functions if f["signature"] == signature), None)

    def has(self, name: str, nparams: int | None = None) -> bool:
        if any(f["name"] == name and (nparams is None or len(f["params"]) == nparams) for f in self.functions):
            return True
        return name in self.getters

    @property
    def is_erc4626(self) -> bool:
        return self.has("asset", 0) and self.has("totalAssets", 0) and any(
            f["signature"] in ERC4626_FLOWS for f in self.flows)


def load_blueprint(path: Path) -> dict:
    try:
        data = json.loads(path.read_text())
    except FileNotFoundError:
        raise SystemExit(f"foundryguard: blueprint not found: {path} (run `foundryguard scan` first)")
    except json.JSONDecodeError as exc:
        raise SystemExit(f"foundryguard: {path} is not valid JSON: {exc}")
    if data.get("schema") not in SUPPORTED_SCHEMAS:
        raise SystemExit(f"foundryguard: unsupported blueprint schema {data.get('schema')!r}, "
                         f"expected one of {', '.join(SUPPORTED_SCHEMAS)}")
    return data


class Index(dict):
    """Blueprint contracts by name (project contracts win over same-named dependencies) and by fqn."""

    def __init__(self, contracts: list[dict]):
        super().__init__()
        self.by_fqn: dict[str, dict] = {}
        for c in contracts:
            if c.get("fqn"):
                self.by_fqn[c["fqn"]] = c
            if c["name"] not in self or (self[c["name"]].get("external") and not c.get("external")):
                self[c["name"]] = c


def linearize(name: str, index: dict[str, dict], _stack: tuple[str, ...] = (), missing: set[str] | None = None,
              contract: dict | None = None) -> list[dict]:
    """Return the contract followed by its ancestors, most-derived first.

    v2 blueprints carry solc's own C3 linearization (``linearized_bases``, by fqn), which is exact even when
    two dependencies define contracts with the same name. v1 blueprints fall back to a name-based walk.
    """
    c = contract or index.get(name)
    by_fqn = getattr(index, "by_fqn", None)
    if c is not None and by_fqn is not None and c.get("linearized_bases"):
        order = [by_fqn.get(f) for f in c["linearized_bases"]]
        if all(o is not None for o in order):
            return order  # type: ignore[return-value]
        if missing is not None:
            missing.update(f.split(":")[-1] for f, o in zip(c["linearized_bases"], order) if o is None)
        return [o for o in order if o is not None]
    if name in _stack:
        return []
    if name not in index:
        if missing is not None:
            missing.add(name)
        return []
    c = index[name]
    order = [c]
    for parent in reversed(c.get("inherits", [])):
        for anc in linearize(parent, index, _stack + (name,), missing):
            if all(anc is not o for o in order):
                order.append(anc)
    return order


def effective_functions(contract: dict, index: dict[str, dict], missing: set[str] | None = None) -> list[dict]:
    """Own + inherited public/external functions, the most-derived definition winning."""
    chosen: dict[str, dict] = {}
    for c in linearize(contract["name"], index, missing=missing, contract=contract) or [contract]:
        for fn in c.get("functions", []):
            if fn["kind"] != "function" or fn["visibility"] not in ("public", "external"):
                continue
            if c["kind"] == "interface" and c is not contract:
                continue  # interfaces declare, they do not implement
            chosen.setdefault(fn["signature"], fn)
    return list(chosen.values())


def _getter_shape_ok(name: str, params: list[str]) -> bool:
    if name in TOTAL_GETTERS + ("totalAssets",):
        return not params
    if name in BALANCE_GETTERS:
        return params == ["address"]
    return True


def collect_getters(contract: dict, index: dict[str, dict], functions: list[dict]) -> set[str]:
    lineage = linearize(contract["name"], index, contract=contract) or [contract]
    getters: set[str] = set()
    for c in lineage:
        getters.update(c.get("accounting_getters", []))
    var_getters = {v["name"]: v.get("getter") for v in collect_state_vars(contract, index)}
    # Only keep getters whose shape we know how to call.
    shaped = set()
    for g in getters:
        fn = next((f for f in functions if f["name"] == g), None)
        if fn is not None:
            if _getter_shape_ok(g, [p["type"] for p in fn["params"]]):
                shaped.add(g)
        elif var_getters.get(g):  # v2: the getter solc generates for the public state variable
            if _getter_shape_ok(g, var_getters[g]["params"]):
                shaped.add(g)
        else:  # v1: public state variable, shape unknown
            shaped.add(g)
    return shaped


def collect_state_vars(contract: dict, index: dict[str, dict]) -> list[dict]:
    """Public state variables of the contract and its ancestors (they have external getters)."""
    out: list[dict] = []
    for c in linearize(contract["name"], index, contract=contract) or [contract]:
        out.extend(v for v in c.get("state_vars", []) if v.get("visibility", "public") == "public")
    return out


def is_admin_only(fn: dict) -> bool:
    return any(ADMIN_MODIFIER.match(m) for m in fn.get("modifiers", []))


def looks_like_plain_token(t: Target) -> bool:
    """A plain ERC-20 whose only 'flows' are mint/burn is a token, not a vault."""
    if t.has("asset", 0):
        return False
    has_erc20 = t.fn("transfer(address,uint256)") and t.fn("approve(address,uint256)")
    # Any ERC-20 base in the lineage (v2: the whole C3 order; v1: direct parents, maybe missing sources).
    token_parent = any(re.match(r"^(ERC20|ERC20Burnable|ERC20Permit|ERC20Votes|ERC20Capped|ERC20Pausable|ERC20Upgradeable)$", p)
                       for p in t.contract.get("inherits", []) + t.lineage[1:])
    if not (has_erc20 or token_parent):
        return False
    return all(re.match(r"^_?(mint|burn)\w*$", f["name"], re.I) for f in t.flows)


def is_custom_candidate(t: Target) -> bool:
    """No preset matched, but there is still something an actor can call that changes state."""
    c = t.contract
    if c.get("abstract") or c.get("deployable") is False or c.get("fully_implemented") is False:
        return False
    return any(f.get("visibility") in ("public", "external") and f.get("mutability") in ("nonpayable", "payable")
               and not is_admin_only(f) and not any(INITIALIZER_MODIFIER.match(m) for m in f.get("modifiers", []))
               for f in t.functions)


def make_target(c: dict, index: "Index", config: dict) -> Target:
    """Effective functions, getters and drivable value flows of one contract."""
    missing: set[str] = set()
    functions = effective_functions(c, index, missing)
    t = Target(contract=c, functions=functions, flows=[], getters=collect_getters(c, index, functions),
               lineage=[x["name"] for x in linearize(c["name"], index, contract=c)],
               settings=config.get("contracts", {}).get(c["name"], {}))
    for m in sorted(missing):
        t.warnings.append(f"parent contract '{m}' was not found, so its functions are invisible "
                          f"(run `forge install` / check remappings, then scan again)")
    for fn in functions:
        if not fn.get("category"):
            continue
        reason = unsupported_reason(fn)
        if reason:
            t.skipped.append((fn["signature"], reason))
        elif is_admin_only(fn):
            t.skipped.append((fn["signature"], f"admin-only ({', '.join(fn['modifiers'])}); not fuzzed from actors"))
        else:
            t.flows.append(fn)
    return t


def build_targets(blueprint: dict, only: set[str] | None, config: dict | None = None,
                  unmatched: list[Target] | None = None) -> list[Target]:
    """Targets the presets can drive. Contracts no preset matches are appended to ``unmatched``."""
    config = config or {}
    tcfg = config.get("targets", {})
    include = set(tcfg.get("include", []))
    exclude = set(tcfg.get("exclude", []))
    index = Index(blueprint["contracts"])

    targets: list[Target] = []
    for c in blueprint["contracts"]:
        if c.get("external") or c.get("test_helper") or c["kind"] != "contract":
            continue
        if only and c["name"] not in only:
            continue
        if c["name"] in exclude:
            log.info("skip %s: excluded in foundryguard.toml", c["name"])
            continue
        t = make_target(c, index, config)
        functions = t.functions
        if t.flows and looks_like_plain_token(t) and c["name"] not in include and not only:
            log.info("skip %s: plain ERC-20 token (mint/burn only); add it to [targets] include to fuzz it", c["name"])
            continue
        if t.flows:
            lineage = linearize(c["name"], index, contract=c) or [c]
            t.hooks = hook_reentrancy.analyze(c["name"], functions, t.flows, lineage, blueprint["contracts"])
            if t.settings.get("transient", True) is not False:
                t.transient = transient_storage.analyze(c["name"], lineage, t.settings)
            t.pricing = flashloan_price.analyze(c["name"], functions, t.flows, lineage, c.get("links", []), t.settings)
            t.governance = governance_flashmint.analyze(c["name"], functions, t.flows, lineage, t.settings)
            # Preset 08 reuses the hook probe to watch a native payout, so it only applies when Preset 04 has
            # not already claimed the actor slot for a declared hook.
            if t.hooks is None:
                rr = read_reentrancy_view.analyze(c["name"], functions, t.flows, lineage, t.settings)
                t.read_reentrancy = rr
                if rr and rr.native:
                    t.hooks = read_reentrancy_view.to_hook_plan(rr)
            for w in t.warnings:
                log.warning("%s: %s", c["name"], w)
            targets.append(t)
        else:
            log.info("skip %s: no drivable deposit/withdraw/stake_lock functions", c["name"])
            for w in t.warnings:
                log.warning("%s: %s", c["name"], w)
            if unmatched is not None and is_custom_candidate(t):
                unmatched.append(t)
    if only:
        missing_names = only - {t.name for t in targets} - {t.name for t in (unmatched or [])}
        for m in sorted(missing_names):
            log.warning("contract %s not found or has no drivable value-flow functions", m)
    return targets


