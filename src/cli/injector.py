UINT_RE = re.compile(r"^uint(\d*)$")
INT_RE = re.compile(r"^int(\d*)$")
BYTESN_RE = re.compile(r"^bytes([1-9]|[12]\d|3[0-2])$")
USER_TYPE_RE = re.compile(r"^[A-Z][\w]*$")


def is_elementary(t: str) -> bool:
    return bool(UINT_RE.match(t) or INT_RE.match(t) or BYTESN_RE.match(t)) or t in ("address", "bool")


def unsupported_reason(fn: dict) -> str | None:
    for p in fn["params"]:
        if not is_elementary(p["type"]):
            return f"parameter '{p['name']}' has non-elementary type '{p['type']}'"
    return None


def sol_ident(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def token_role(name: str) -> str:
    n = name.lower()
    if "reward" in n:
        return "reward"
    if "stak" in n or "lp" == n.strip("_"):
        return "staking"
    return "asset"


def is_token_param(p: dict) -> bool:
    t, name = p["type"], p["name"]
    if TOKEN_TYPES.match(t):
        return True
    return t == "address" and bool(TOKEN_ADDR_NAME.search(name)) and not OWNER_NAME.match(name)


def default_value(t: str, name: str) -> tuple[str | None, str | None]:
    """Return (Solidity expression, warning) for a constructor/initializer argument."""
    n = name.lower()
    if UINT_RE.match(t):
        bits = int(UINT_RE.match(t).group(1) or 256)
        if "decimal" in n:
            return "18", None
        if re.search(r"fee|bps|tax|basis", n):
            return "0", None
        if re.search(r"duration|period|delay|cooldown|window|interval", n):
            return ("7 days" if bits >= 32 else "1"), None
        return ("1e18" if bits >= 64 else "1"), None
    if INT_RE.match(t):
        return "1", None
    if t == "address":
        return "address(this)", None
    if t == "bool":
        return "false", None
    if BYTESN_RE.match(t):
        return f"{t}(0)", None
    if t == "string":
        return f'"{name.strip("_") or "FoundryGuard"}"', None
    if t == "bytes":
        return '""', None
    m = re.match(r"^(.+)\[\d*\]$", t)
    if m and (is_elementary(m.group(1)) or m.group(1) in ("string", "bytes")):
        return f"new {m.group(1)}[](0)", None
    if USER_TYPE_RE.match(t):  # contract / interface typed address, e.g. IOracle
        return "address(this)", f"'{name}' ({t}) is a placeholder address(this): pass a real or mock {t}"
    return None, f"cannot build a default for '{name}' of type '{t}'"


@dataclass
class Arg:
    fuzz_decl: str | None   # handler parameter, e.g. "uint256 amountSeed"
    prelude: list[str]      # lines computing the value
    expr: str               # expression passed to the target
    raw: str | None = None  # uint256 value before narrowing casts (for ghost accounting)


def outbound_bound(t: Target, fn: dict) -> str | None:
    """Expression for the largest amount this actor can take out, when the contract tells us."""
    sig = fn["signature"]
    if sig == "withdraw(uint256,address,address)" and t.has("maxWithdraw", 1):
        return "target.maxWithdraw(actor)"
    if sig == "redeem(uint256,address,address)" and t.has("maxRedeem", 1):
        return "target.maxRedeem(actor)"
    if fn["direction"] != "out" or not fn.get("amount_param"):
        return None
    order = STAKE_BALANCE_GETTERS if fn["category"] == "stake_lock" else ("balanceOf", "sharesOf", "stakedOf", "lockedOf")
    g = next((g for g in order if g in t.getters), None)
    return f"target.{g}(actor)" if g else None


def build_arg(t: Target, fn: dict, p: dict, i: int, max_amount: str) -> Arg:
    ptype, name = p["type"], sol_ident(p["name"]) or f"arg{i}"
    var = f"{name}_"
    m = UINT_RE.match(ptype)
    if m:
        bits = int(m.group(1) or 256)
        seed = f"{name}Seed"
        if p["name"] == fn.get("amount_param"):
            cap = max_amount if bits >= 80 else f"type(uint{bits}).max"
            upper = outbound_bound(t, fn)
            if upper:
                lines = [f"uint256 {var}max = {upper};",
                         f"if ({var}max == 0) {{",
                         "    ghost_skipped++;",
                         "    return;",
                         "}",
                         f"uint256 {var} = bound({seed}, 1, {var}max < {cap} ? {var}max : {cap});"]
            else:
                lines = [f"uint256 {var} = bound({seed}, 1, {cap});"]
            return Arg(f"uint256 {seed}", lines, _cast(var, bits), var)
        if bits == 256:
            return Arg(f"uint256 {seed}", [], seed, seed)
        return Arg(f"uint256 {seed}", [f"uint256 {var} = bound({seed}, 0, type(uint{bits}).max);"], _cast(var, bits), var)
    m = INT_RE.match(ptype)
    if m:
        return Arg(f"{ptype} {name}Seed", [], f"{name}Seed")
    if ptype == "address":
        # The caller's own position (owner/from/account) must be the pranked actor, or the call needs an
        # allowance. Receivers are routed back into the actor set so value stays observable.
        if SELF_ADDR_PARAM.match(p["name"]):
            return Arg(None, [], "actor")
        seed = f"{name}Seed"
        return Arg(f"uint256 {seed}", [], f"_actor({seed})")
    if ptype == "bool" or BYTESN_RE.match(ptype):
        return Arg(f"{ptype} {name}Seed", [], f"{name}Seed")
    raise ValueError(f"unsupported type {ptype}")


def _cast(var: str, bits: int) -> str:
    return var if bits == 256 else f"uint{bits}({var})"


