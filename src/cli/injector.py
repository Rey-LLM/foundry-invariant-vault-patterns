#!/usr/bin/env python3
"""FoundryGuard injector: turn a parser blueprint into Foundry invariant test suites.

For every deployable contract in the blueprint that exposes at least one
deposit, withdraw or staking/lock function (directly or through inheritance),
the injector writes two files::

    <out>/<Contract>/Handler.sol         fuzz handler with bounded inputs, actor
                                          pranking and ghost accounting
    <out>/<Contract>/Invariant.t.sol     invariant suite wired to the handler

Generated handlers wrap every call in try/catch, so a target that rejects an
input (missing approval, paused, cooldown, ...) is recorded as a revert in the
ghost state instead of aborting the run under ``fail_on_revert = true``.
Ghost totals only move when the call succeeds.

Invariants are emitted only when the blueprint proves they are meaningful:

* ``invariant_withdrawalsBoundedByDeposits`` - when every value-flow function
  measures its amount in the same unit (assets, shares or native) and the
  contract has both an inbound and an outbound flow. Mixed-unit surfaces such
  as ERC-4626 (deposit/withdraw in assets, mint/redeem in shares) skip it,
  because the ghost totals would not be comparable.
* ``invariant_actorBalancesBoundedByTotal`` - when the contract exposes
  ``balanceOf(address)`` plus ``totalSupply()``/``totalStaked()``/... getters.
* ``afterInvariant`` - always; fails a run in which every value-flow call
  reverted, which signals a setUp that still needs funding or approvals.

Usage::

    python3 src/cli/injector.py foundryguard.json
    python3 src/cli/injector.py foundryguard.json --out test/foundryguard --contract StakingPool
    python3 src/cli/injector.py foundryguard.json --dry-run
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

SUPPORTED_SCHEMA = "foundryguard.blueprint/v1"
GENERATED_MARKER = "// @generated by FoundryGuard"
DEFAULT_ACTORS = 4
DEFAULT_MAX_AMOUNT = "1e24"
DEFAULT_PRAGMA = "^0.8.20"

log = logging.getLogger("foundryguard.injector")

TOTAL_GETTERS = ("totalStaked", "totalLocked", "totalDeposits", "totalSupply")
BALANCE_GETTERS = ("balanceOf", "stakedOf", "lockedOf", "sharesOf")


# --------------------------------------------------------------------------- #
# Blueprint access
# --------------------------------------------------------------------------- #


@dataclass
class Target:
    contract: dict
    functions: list[dict]           # effective public/external functions (own + inherited)
    flows: list[dict]               # classified value-flow functions to drive
    skipped: list[tuple[str, str]] = field(default_factory=list)  # (signature, reason)
    getters: set[str] = field(default_factory=set)

    @property
    def name(self) -> str:
        return self.contract["name"]


def load_blueprint(path: Path) -> dict:
    try:
        data = json.loads(path.read_text())
    except FileNotFoundError:
        raise SystemExit(f"foundryguard: blueprint not found: {path} (run parser.py first)")
    except json.JSONDecodeError as exc:
        raise SystemExit(f"foundryguard: {path} is not valid JSON: {exc}")
    if data.get("schema") != SUPPORTED_SCHEMA:
        raise SystemExit(f"foundryguard: unsupported blueprint schema {data.get('schema')!r}, expected {SUPPORTED_SCHEMA!r}")
    return data


def linearize(name: str, index: dict[str, dict], _stack: tuple[str, ...] = ()) -> list[dict]:
    """Return the contract followed by its ancestors, most-derived first (simplified C3)."""
    if name in _stack or name not in index:
        return []
    c = index[name]
    order = [c]
    for parent in reversed(c.get("inherits", [])):
        for anc in linearize(parent, index, _stack + (name,)):
            if all(anc is not o for o in order):
                order.append(anc)
    return order


def effective_functions(contract: dict, index: dict[str, dict]) -> list[dict]:
    """Own + inherited public/external functions, the most-derived definition winning."""
    chosen: dict[str, dict] = {}
    for c in linearize(contract["name"], index) or [contract]:
        for fn in c.get("functions", []):
            if fn["kind"] != "function" or fn["visibility"] not in ("public", "external"):
                continue
            if c["kind"] == "interface" and c is not contract:
                continue  # interfaces declare, they do not implement
            chosen.setdefault(fn["signature"], fn)
    return list(chosen.values())


def collect_getters(contract: dict, index: dict[str, dict], functions: list[dict]) -> set[str]:
    getters: set[str] = set()
    for c in linearize(contract["name"], index) or [contract]:
        getters.update(c.get("accounting_getters", []))
    # Only keep getters whose shape we know how to call.
    shaped = set()
    for g in getters:
        fn = next((f for f in functions if f["name"] == g), None)
        if fn is None:  # public state variable getter
            shaped.add(g)
        elif g in TOTAL_GETTERS and not fn["params"]:
            shaped.add(g)
        elif g in BALANCE_GETTERS and [p["type"] for p in fn["params"]] == ["address"]:
            shaped.add(g)
    return shaped


def build_targets(blueprint: dict, only: set[str] | None) -> list[Target]:
    index: dict[str, dict] = {}
    for c in blueprint["contracts"]:
        # Prefer project contracts over same-named library contracts.
        if c["name"] not in index or (index[c["name"]].get("external") and not c.get("external")):
            index[c["name"]] = c

    targets: list[Target] = []
    for c in blueprint["contracts"]:
        if c.get("external") or c.get("test_helper") or c["kind"] != "contract":
            continue
        if only and c["name"] not in only:
            continue
        functions = effective_functions(c, index)
        t = Target(contract=c, functions=functions, flows=[], getters=collect_getters(c, index, functions))
        for fn in functions:
            if not fn.get("category"):
                continue
            reason = unsupported_reason(fn)
            if reason:
                t.skipped.append((fn["signature"], reason))
            else:
                t.flows.append(fn)
        if t.flows:
            targets.append(t)
        else:
            log.info("skip %s: no drivable deposit/withdraw/stake_lock functions", c["name"])
    if only:
        missing = only - {t.name for t in targets}
        for m in sorted(missing):
            log.warning("contract %s not found or has no drivable value-flow functions", m)
    return targets


# --------------------------------------------------------------------------- #
# Solidity type handling
# --------------------------------------------------------------------------- #

UINT_RE = re.compile(r"^uint(\d*)$")
INT_RE = re.compile(r"^int(\d*)$")
BYTESN_RE = re.compile(r"^bytes([1-9]|[12]\d|3[0-2])$")


def unsupported_reason(fn: dict) -> str | None:
    for p in fn["params"]:
        t = p["type"]
        if not (UINT_RE.match(t) or INT_RE.match(t) or BYTESN_RE.match(t) or t in ("address", "bool")):
            return f"parameter '{p['name']}' has non-elementary type '{t}'"
    return None


def sol_ident(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


@dataclass
class Arg:
    fuzz_decl: str | None   # handler parameter, e.g. "uint256 amountSeed"
    prelude: list[str]      # lines computing the value
    expr: str               # expression passed to the target


def build_arg(fn: dict, p: dict, i: int, max_amount: str) -> Arg:
    t, name = p["type"], sol_ident(p["name"]) or f"arg{i}"
    var = f"{name}_"
    m = UINT_RE.match(t)
    if m:
        bits = int(m.group(1) or 256)
        seed = f"{name}Seed"
        if p["name"] == fn.get("amount_param"):
            cap = max_amount if bits >= 80 else f"type(uint{bits}).max"
            return Arg(f"uint256 {seed}", [f"uint256 {var} = bound({seed}, 1, {cap});"], _cast(var, bits))
        if bits == 256:
            return Arg(f"uint256 {seed}", [], seed)
        return Arg(f"uint256 {seed}", [f"uint256 {var} = bound({seed}, 0, type(uint{bits}).max);"], _cast(var, bits))
    m = INT_RE.match(t)
    if m:
        return Arg(f"{t} {name}Seed", [], f"{name}Seed")
    if t == "address":
        # Receivers/owners/recipients are routed back into the actor set so value stays observable.
        seed = f"{name}Seed"
        return Arg(f"uint256 {seed}", [], f"_actor({seed})")
    if t == "bool" or BYTESN_RE.match(t):
        return Arg(f"{t} {name}Seed", [], f"{name}Seed")
    raise ValueError(f"unsupported type {t}")


def _cast(var: str, bits: int) -> str:
    return var if bits == 256 else f"uint{bits}({var})"


def default_ctor_value(t: str, name: str) -> str:
    if UINT_RE.match(t):
        return "1e18" if int(UINT_RE.match(t).group(1) or 256) >= 64 else "1"
    if INT_RE.match(t):
        return "1"
    if t == "address":
        return "address(this)"
    if t == "bool":
        return "false"
    if BYTESN_RE.match(t):
        return f"{t}(0)"
    if t == "string":
        return f'"{name}"'
    if t == "bytes":
        return '""'
    if re.match(r"^[A-Z]\w*$", t):  # contract / interface typed address, e.g. IERC20
        return f"{t}(address(this))"
    return f"/* FOUNDRYGUARD: provide {t} */ {t}(0)"


# --------------------------------------------------------------------------- #
# Code generation
# --------------------------------------------------------------------------- #


def import_path(from_dir: Path, root: Path, src_file: str) -> str:
    rel = os.path.relpath(root / src_file, from_dir).replace(os.sep, "/")
    return rel if rel.startswith(".") else f"./{rel}"


def pragma_for(contract: dict) -> str:
    return contract.get("pragma") or DEFAULT_PRAGMA


def handler_fn_name(fn: dict, used: set[str]) -> str:
    base = fn["name"]
    name, k = base, 2
    while name in used:
        name, k = f"{base}_{k}", k + 1
    used.add(name)
    return name


def render_handler(t: Target, import_rel: str, actors: int, max_amount: str) -> tuple[str, list[str]]:
    c = t.contract
    units = sorted({f["unit"] for f in t.flows if f.get("unit")})
    used: set[str] = set()
    wrappers: list[str] = []
    selectors: list[str] = []

    for fn in t.flows:
        hname = handler_fn_name(fn, used)
        selectors.append(hname)
        args = [build_arg(fn, p, i, max_amount) for i, p in enumerate(fn["params"])]
        decls = ["uint256 actorSeed"] + [a.fuzz_decl for a in args if a.fuzz_decl]
        if fn["mutability"] == "payable":
            decls.append("uint256 valueSeed")
        body = ["address actor = _actor(actorSeed);"]
        for a in args:
            body.extend(a.prelude)
        call_opts = ""
        if fn["mutability"] == "payable":
            body.append(f"uint256 value_ = bound(valueSeed, {'1' if fn.get('unit') == 'native' else '0'}, {max_amount});")
            body.append("vm.deal(actor, actor.balance + value_);")
            call_opts = "{value: value_}"
        call_args = ", ".join(a.expr for a in args)

        amount_expr = None
        if fn.get("amount_param") == "msg.value":
            amount_expr = "value_"
        elif fn.get("amount_param"):
            idx = next(i for i, p in enumerate(fn["params"]) if p["name"] == fn["amount_param"])
            amount_expr = args[idx].expr
            if amount_expr.startswith("uint") and "(" in amount_expr:
                amount_expr = amount_expr[amount_expr.index("(") + 1 : -1]

        on_success = [f"ghost_calls[{_q(hname)}]++;", "ghost_successfulFlows++;"]
        if amount_expr and fn.get("unit"):
            if fn["direction"] == "in":
                on_success.append(f"ghost_in[{_q(fn['unit'])}] += {amount_expr};")
            elif fn["direction"] == "out":
                on_success.append(f"ghost_out[{_q(fn['unit'])}] += {amount_expr};")

        body.append("vm.prank(actor);")
        body.append(f"try target.{fn['name']}{call_opts}({call_args}) {{")
        body.extend("    " + s for s in on_success)
        body.append("} catch {")
        body.append(f"    ghost_reverts[{_q(hname)}]++;")
        body.append("}")

        doc = f"/// @notice {fn['category']} ({fn['direction']}) -> {c['name']}.{fn['signature']}"
        wrappers.append(
            f"    {doc}\n    function {hname}({', '.join(decls)}) external {{\n"
            + "\n".join("        " + line for line in body)
            + "\n    }"
        )

    units_init = "\n".join(f'        units.push("{u}");' for u in units)
    skipped = "".join(f"\n/// - skipped {sig}: {why}" for sig, why in t.skipped)
    src = f"""// SPDX-License-Identifier: MIT
pragma solidity {pragma_for(c)};

{GENERATED_MARKER} from {c['file']}:{c['line']}. Edit freely: the injector only overwrites with --force.

import {{ CommonBase }} from "forge-std/Base.sol";
import {{ StdUtils }} from "forge-std/StdUtils.sol";
import {{ {c['name']} }} from "{import_rel}";

/// @title {c['name']}GuardHandler
/// @notice Drives {c['name']} through its deposit / withdraw / staking-lock surface with a fixed actor
///         set and bounded inputs. Ghost totals advance only on successful calls; reverts are counted
///         per selector so `forge test --show-metrics` and afterInvariant() expose a stuck setup.{skipped}
contract {c['name']}GuardHandler is CommonBase, StdUtils {{
    {c['name']} public immutable target;

    uint256 public constant MAX_AMOUNT = {max_amount};

    address[] public actors;
    string[] public units;

    /// Sum of successful inbound amounts, keyed by unit ("assets", "shares", "native").
    mapping(string => uint256) public ghost_in;
    /// Sum of successful outbound amounts, keyed by unit.
    mapping(string => uint256) public ghost_out;
    mapping(string => uint256) public ghost_calls;
    mapping(string => uint256) public ghost_reverts;
    uint256 public ghost_successfulFlows;

    constructor({c['name']} _target) {{
        target = _target;
        for (uint256 i = 0; i < {actors}; i++) {{
            actors.push(address(uint160(0xF0A0 + i)));
        }}
{units_init}
    }}

    function actorCount() external view returns (uint256) {{
        return actors.length;
    }}

    function unitCount() external view returns (uint256) {{
        return units.length;
    }}

{chr(10).join(chr(10).join([w, '']) for w in wrappers).rstrip()}

    /// @notice Advances time so time-weighted rewards and lock expiries are exercised.
    function warp(uint256 dtSeed) external {{
        vm.warp(block.timestamp + bound(dtSeed, 1, 7 days));
        vm.roll(block.number + 1);
    }}

    function _actor(uint256 seed) internal view returns (address) {{
        return actors[bound(seed, 0, actors.length - 1)];
    }}
}}
"""
    return src, selectors + ["warp"]


def render_invariant(t: Target, import_rel: str, selectors: list[str]) -> str:
    c = t.contract
    hname = f"{c['name']}GuardHandler"
    ctor = c.get("constructor")
    ctor_args = ", ".join(default_ctor_value(p["type"], p["name"]) for p in (ctor["params"] if ctor else []))
    ctor_note = (
        "        // FOUNDRYGUARD: placeholder constructor arguments - replace with real dependencies\n"
        "        // (tokens, oracles, owners) and fund/approve the handler actors below if the target pulls tokens.\n"
        if ctor and ctor["params"] else ""
    )
    ctor_value = "{value: 0}" if ctor and ctor.get("mutability") == "payable" else ""

    units = {f["unit"] for f in t.flows if f.get("unit")}
    directions = {f["direction"] for f in t.flows if f.get("unit")}
    invariants: list[str] = []

    if len(units) == 1 and {"in", "out"} <= directions:
        unit = next(iter(units))
        invariants.append(f"""    /// @notice Successful outbound {unit} never exceed successful inbound {unit}.
    /// @dev Relax this bound if {c['name']} pays yield in the same unit it accepts.
    function invariant_withdrawalsBoundedByDeposits() public view {{
        assertLe(handler.ghost_out("{unit}"), handler.ghost_in("{unit}"), "{unit}: more left than entered");
    }}""")

    total = next((g for g in TOTAL_GETTERS if g in t.getters), None)
    balance = next((g for g in BALANCE_GETTERS if g in t.getters), None)
    if total and balance:
        invariants.append(f"""    /// @notice The sum of actor balances never exceeds the reported total.
    function invariant_actorBalancesBoundedByTotal() public view {{
        uint256 sum;
        for (uint256 i = 0; i < handler.actorCount(); i++) {{
            sum += target.{balance}(handler.actors(i));
        }}
        assertLe(sum, target.{total}(), "{balance} sum exceeds {total}");
    }}""")

    invariants.append("""    /// @notice Runs once per fuzz run: if no value-flow call ever succeeded, the invariants above
    ///         were checked against an untouched contract. Fund and approve the actors in setUp.
    function afterInvariant() public view {
        assertGt(handler.ghost_successfulFlows(), 0, "no value-flow call succeeded: fix setUp funding/approvals");
    }""")

    selector_lines = "\n".join(f"        selectors[{i}] = {hname}.{s}.selector;" for i, s in enumerate(selectors))
    handler_import = "./Handler.sol"
    return f"""// SPDX-License-Identifier: MIT
pragma solidity {pragma_for(c)};

{GENERATED_MARKER} from {c['file']}:{c['line']}

import {{ Test }} from "forge-std/Test.sol";
import {{ {c['name']} }} from "{import_rel}";
import {{ {hname} }} from "{handler_import}";

/// @title {c['name']}GuardInvariantTest
/// @notice Stateful invariant suite generated by FoundryGuard for {c['name']}.
contract {c['name']}GuardInvariantTest is Test {{
    {c['name']} internal target;
    {hname} internal handler;

    function setUp() public {{
{ctor_note}        target = new {c['name']}{ctor_value}({ctor_args});
        handler = new {hname}(target);

        bytes4[] memory selectors = new bytes4[]({len(selectors)});
{selector_lines}

        targetContract(address(handler));
        targetSelector(FuzzSelector({{ addr: address(handler), selectors: selectors }}));
        excludeContract(address(target));
    }}

{chr(10).join(chr(10).join([inv, '']) for inv in invariants).rstrip()}
}}
"""


def _q(s: str) -> str:
    return '"' + s.replace('"', '\\"') + '"'


# --------------------------------------------------------------------------- #
# Writing
# --------------------------------------------------------------------------- #


def write_file(path: Path, content: str, force: bool, dry_run: bool) -> str:
    if path.exists():
        existing = path.read_text()
        if existing == content:
            return "unchanged"
        if not force:
            return "kept (exists, use --force to overwrite)"
    if dry_run:
        return "would write"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    return "written"


def inject(blueprint: dict, root: Path, out_dir: Path, only: set[str] | None, actors: int,
           max_amount: str, force: bool, dry_run: bool) -> list[dict]:
    report = []
    for t in build_targets(blueprint, only):
        dest = (out_dir / t.name).resolve()
        import_rel = import_path(dest, root, t.contract["file"])
        handler_src, selectors = render_handler(t, import_rel, actors, max_amount)
        invariant_src = render_invariant(t, import_rel, selectors)
        h_status = write_file(dest / "Handler.sol", handler_src, force, dry_run)
        i_status = write_file(dest / "Invariant.t.sol", invariant_src, force, dry_run)
        report.append({
            "contract": t.name,
            "dir": dest.as_posix(),
            "handler": h_status,
            "invariant": i_status,
            "flows": [f"{f['category']}:{f['signature']}" for f in t.flows],
            "skipped": [f"{s} ({r})" for s, r in t.skipped],
        })
    return report


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="foundryguard-inject",
        description="Generate Foundry Handler.sol / Invariant.t.sol suites from a FoundryGuard blueprint.",
    )
    ap.add_argument("blueprint", nargs="?", default="foundryguard.json", help="blueprint from parser.py (default: foundryguard.json)")
    ap.add_argument("--root", help="project root (default: the root recorded in the blueprint)")
    ap.add_argument("--out", default="test/foundryguard", help="output dir, relative to root (default: test/foundryguard)")
    ap.add_argument("--contract", action="append", help="only generate for this contract (repeatable)")
    ap.add_argument("--actors", type=int, default=DEFAULT_ACTORS, help=f"number of fuzz actors (default: {DEFAULT_ACTORS})")
    ap.add_argument("--max-amount", default=DEFAULT_MAX_AMOUNT, help=f"upper bound for amount params (default: {DEFAULT_MAX_AMOUNT})")
    ap.add_argument("--force", action="store_true", help="overwrite existing files")
    ap.add_argument("--dry-run", action="store_true", help="print what would be generated without writing")
    ap.add_argument("--json", action="store_true", help="print the generation report as JSON")
    ap.add_argument("-v", "--verbose", action="count", default=0)
    args = ap.parse_args(argv)

    logging.basicConfig(level=logging.WARNING - 10 * min(args.verbose, 2), format="%(levelname)s %(name)s: %(message)s")
    if args.actors < 1:
        ap.error("--actors must be >= 1")
    if not re.fullmatch(r"\d+(e\d+)?", args.max_amount):
        ap.error("--max-amount must be a Solidity number literal such as 1e24")

    blueprint = load_blueprint(Path(args.blueprint))
    root = Path(args.root or blueprint.get("root") or ".").resolve()
    out_dir = Path(args.out)
    out_dir = out_dir if out_dir.is_absolute() else root / out_dir
    report = inject(blueprint, root, out_dir, set(args.contract) if args.contract else None,
                    args.actors, args.max_amount, args.force, args.dry_run)

    if args.json:
        print(json.dumps(report, indent=2))
    else:
        if not report:
            print("foundryguard: no contracts with drivable deposit/withdraw/stake_lock functions", file=sys.stderr)
        for r in report:
            print(f"{r['contract']}: Handler.sol {r['handler']}, Invariant.t.sol {r['invariant']} -> {os.path.relpath(r['dir'])}")
            for f in r["flows"]:
                print(f"    + {f}")
            for s in r["skipped"]:
                print(f"    - {s}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
